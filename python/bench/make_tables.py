def tab_e2e(d: Data) -> str:
    L = ["\\toprule",
         "Model & Sites & Mode & \\multicolumn{2}{c}{Preprocessing} & \\multicolumn{5}{c}{Online} & Total & Exact & Agree \\\\",
         "\\cmidrule(lr){4-5}\\cmidrule(lr){6-10}",
         " & & & GB/party & s & Rounds & KB/party & s & s (20\\,ms) & s (80\\,ms) & s (80\\,ms) & runs & \\% \\\\",
         "\\midrule"]
    for preset in E2E_TABLE_MODELS:
        for mode in rc.MODES:
            r = d.row(infer_name(preset, 16, 8, mode), "tab-e2e")
            if not r:
                continue
            w20 = d.row(infer_name(preset, 16, 8, mode, link="wan20"), "tab-e2e")
            w80 = d.row(infer_name(preset, 16, 8, mode, link="wan80"), "tab-e2e")
            acc = d.accuracy(rc.model_name(preset, 16, 8))
            c = _e2e_cells(r, acc)
            label = MODEL_TEXT[preset] if mode == "round" else ""
            sites = f_int(r["sites"]) if mode == "round" else ""
            link_cells = []
            for link, lr, key in (("wan20", w20, "online_seconds"), ("wan80", w80, "online_seconds"),
                                  ("wan80", w80, "seconds")):
                if lr:
                    link_cells.append(f_sig(lr[key]))
                    continue
                lname = infer_name(preset, 16, 8, mode, link=link)
                if any(x["id"] == "e2e/" + lname for x in d.s.get("not_measured", [])):
                    v = link_estimate(r, link)[key]
                    link_cells.append(est(f_sig(v)))
                    d.estimated.append(("tab-e2e", lname, key, f_sig(v).replace("{,}", ","), LINK_RULE))
                else:
                    link_cells.append("--")
            L.append(f"{label} & {sites} & $\\m{mode}$ & {c[0]} & {c[1]} & {c[2]} & {c[3]} & {c[4]} & "
                     f"{link_cells[0]} & {link_cells[1]} & {link_cells[2]} & {c[6]} & {c[7]} \\\\")
    priv = []
    for preset in E2E_TABLE_PRIVATE:
        for mode in rc.MODES:
            r = d.row(infer_name(preset, 16, 8, mode, private=True), "tab-e2e")
            if r:
                c = _e2e_cells(r, d.accuracy(rc.model_name(preset, 16, 8)))
                label = MODEL_TEXT[preset] + ", private" if mode == "round" else ""
                priv.append(f"{label} & {f_int(r['sites']) if mode == 'round' else ''} & $\\m{mode}$ & {c[0]} & {c[1]} & "
                            f"{c[2]} & {c[3]} & {c[4]} & -- & -- & -- & {c[6]} & {c[7]} \\\\")
    for preset in rc.LARGEST:                # private-model rows of summary.json not_measured: red cells
        for mode in rc.MODES:
            e = private_estimate(d, preset, mode)
            if not e:
                continue
            acc = d.accuracy(rc.model_name(preset, 16, 8))
            agree = f_pct(acc["prediction_agreement"] if mode == "exact" else acc["prediction_agreement_round"]) if acc else "--"
            cells = [("prep_gb", f_sig(e["prep_gb"])), ("prep_s", f_sig(e["prep_s"])), ("online_rounds", f_int(e["online_rounds"])),
                     ("online_kb", f_sig(e["online_kb"])), ("online_s", f_sig(e["online_s"]))]
            for key, v in cells:
                d.estimated.append(("tab-e2e", e["name"], key, v.replace("{,}", ","), PRIVATE_RULE))
            priv.append(f"{MODEL_TEXT[preset]}, private & {f_int(e['sites'])} & $\\m{mode}$ & "
                        + " & ".join(est(v) for _, v in cells) + f" & -- & -- & -- & -- & {agree} \\\\")
    if priv:
        L.append("\\midrule")
        L += priv
    thr = []
    for preset in (rc.LARGEST if E2E_TABLE_THREADS else ()):
        for mode in rc.MODES:
            r = d.row(infer_name(preset, 16, 8, mode, threads=8), "tab-e2e")
            if r:
                c = _e2e_cells(r, d.accuracy(rc.model_name(preset, 16, 8)))
                label = MODEL_TEXT[preset] + ", 8 threads" if mode == "round" else ""
                thr.append(f"{label} & {f_int(r['sites']) if mode == 'round' else ''} & $\\m{mode}$ & {c[0]} & {c[1]} & "
                           f"{c[2]} & {c[3]} & {c[4]} & -- & -- & -- & {c[6]} & {c[7]} \\\\")
    if thr:
        L.append("\\midrule")
        L += thr
    L.append("\\bottomrule")
    return _tab("lrlrrrrrrrrrr", L,
                "Float: table* (full width), tab:e2e.  (n, f) = (16, 8), k = s = 64, sigma = 40, one thread unless "
                "stated; Preprocessing = everything before the online phase on the link without delay (manifest, OT, "
                "triples, generation circuits); Online s at no delay and at 20 / 80 ms round-trip time with 100 Mbit/s "
                "per direction; Total s (80 ms) = the whole session on that link; Exact runs = runs whose logits equal "
                "the fixed-point mirror bit for bit (no-delay row); Agree = prediction agreement of the fixed-point "
                "mirror with the float model on the 2,048 synthetic test inputs.  Cells in \\est{...} (red): "
                "configurations of summary.json not_measured, computed by link_estimate / private_estimate "
                "(PROVENANCE.md).")


def tab_e2e_all(d: Data) -> str:
    L = ["\\toprule",
         "Model & $(n,f)$ & Mode & Link & Thr. & \\multicolumn{2}{c}{Preprocessing} & \\multicolumn{3}{c}{Online} & Total & Exact \\\\",
         "\\cmidrule(lr){6-7}\\cmidrule(lr){8-10}",
         " & & & RTT & & GB/party & s & Rounds & KB/party & s & s & runs \\\\", "\\midrule"]
    rows = [r for r in d.s.get("e2e", []) if r.get("status") == "ok"]
    order = {p: i for i, p in enumerate(list(rc.E2E_MODELS) + ["mlp784h1", "mlp784h3"])}
    rows.sort(key=lambda r: (order.get(r["preset"], 99), -r["config"]["n"], r["config"]["private_model"],
                             list(rc.LINKS).index(r["config"]["link"]), r["config"]["threads"], r["config"]["mode"] != "round"))
    for r in rows:
        cfg = r["config"]
        c = _e2e_cells(r, None)
        label = MODEL_TEXT[r["preset"]] + (", private" if cfg["private_model"] else "")
        L.append(f"{label} & $({cfg['n']},{cfg['f']})$ & $\\m{cfg['mode']}$ & {LINK_TEXT[cfg['link']]} & {cfg['threads']} & "
                 f"{c[0]} & {c[1]} & {c[2]} & {c[3]} & {c[4]} & {c[5]} & {c[6]} \\\\")
    for r in d.s.get("e2e", []):
        if r.get("status") != "ok":
            d.left_out.append(("tab-e2e-all", r["name"], r["status"], r.get("reason", "")))
    L.append("\\bottomrule")
    return _tab("llllrrrrrrrr", L, "Float: table* (full width), appendix.  Every accepted end-to-end row of the campaign; "
                                   "the link is the round-trip time at 100 Mbit/s per direction ('none': loopback).")


def tab_attacks(d: Data) -> str:
    L = ["\\toprule", "Deviation & Trials & Aborts & Released & Wrong & $|z|$ \\\\", "\\midrule"]
    names = {"deferred": "Wrong deferred opening", "deferred-high": "Deferred, error $2^{m-1}$",
             "release": "Wrong logit opening", "release-high": "Logit, error $2^{w-1}$",
             "first-layer": "First-layer substitution", "wrong-key": "Foreign plane key", "replay": "Replayed opening",
             "tiny-guess": "MAC guess, $s=4$"}
    if d.ppml:
        for r in d.ppml.get("rows", []):
            L.append(f"{names.get(r['id'], r['id'])} & {f_int(r['trials'])} & {f_int(r['detected'])} & "
                     f"{f_int(r['honest_outputs_released'])} & {f_int(r['wrong_outputs_accepted'])} & {f_fix(abs(r['z']), 2)} \\\\")

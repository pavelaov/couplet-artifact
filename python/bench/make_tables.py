LINK_RULE = ("total = no-delay .seconds + max(.bytes_sent_p0, .bytes_sent_p1) * 8 / rate + .rounds * delay; "
             "online = no-delay .online_seconds + max(.online_bytes_p0, .online_bytes_p1) * 8 / rate "
             "+ .online_rounds * delay (rate = 100 Mbit/s per direction, delay = one-way delay of the link)")


def link_estimate(lan: dict, link: str) -> dict:
    """Seconds of a no-delay row on an emulated link: the loopback time, plus the transfer time of the busier
    direction at the link's rate, plus one one-way delay per round (LINK_RULE)."""
    delay_ms, mbps = rc.LINKS[link]
    rate = mbps * 1e6 / 8.0
    delay = delay_ms / 1e3
    return {"seconds": lan["seconds"] + max(lan["bytes_sent_p0"], lan["bytes_sent_p1"]) / rate + lan["rounds"] * delay,
            "online_seconds": (lan["online_seconds"] + max(lan["online_bytes_p0"], lan["online_bytes_p1"]) / rate
                               + lan["online_rounds"] * delay)}


def link_model_check(d: "Data") -> dict:
    """Ratio measured / LINK_RULE over every accepted link row whose no-delay row exists (the rule's error)."""
    rows = {r["name"]: r for r in d.s.get("e2e", []) if r.get("status") == "ok"}
    tot, on = [], []
    for name, r in rows.items():
        link = r["config"].get("link")
        if link in (None, "lan"):
            continue
        cfg = dict(r["config"])
        lan = rows.get(infer_name(r["preset"], cfg["n"], cfg["f"], cfg["mode"], private=cfg["private_model"],
                                  threads=cfg["threads"]))
        if not lan:
            continue
        e = link_estimate(lan, link)
        tot.append(r["seconds"] / e["seconds"])
        on.append(r["online_seconds"] / e["online_seconds"])
    return {"rows": len(tot), "total": (min(tot), max(tot)) if tot else None,
            "online": (min(on), max(on)) if on else None}


PRIVATE_RULE = ("AND gates = not_measured[...].estimate.and_gates_needed (compiler fits of the matrix triples and "
                "input masks, plus the sites and output masks); prep bytes per party = AND gates * the public-model "
                "row's .prep_bytes_per_party_max / .and_gates; prep s = AND gates / (the public-model row's .and_gates "
                "/ .prep_seconds); online rounds = .online_rounds of the measured private-model rows (all equal; the "
                "same three linear layers); online bytes and seconds = the public-model row's value + a line through "
                "the private-minus-public differences of the two measured private-model rows against their numbers "
                "of weights, at the model's weights")


def private_estimate(d: "Data", preset: str, mode: str):
    """Red cells of a private-model row that was not measured (PRIVATE_RULE), or None without the inputs."""
    name = infer_name(preset, 16, 8, mode, private=True)
    nm = next((r for r in d.s.get("not_measured", []) if r["id"] == "e2e/" + name), None)
    pub = d.rows.get(infer_name(preset, 16, 8, mode))
    pts = []
    for p in rc.PRIVATE_MODELS:
        pr, pp = d.rows.get(infer_name(p, 16, 8, mode, private=True)), d.rows.get(infer_name(p, 16, 8, mode))
        if pr and pp and pr.get("status") == "ok" and pp.get("status") == "ok":
            pts.append((pr["weights"], max(pr["online_bytes_p0"], pr["online_bytes_p1"])
                        - max(pp["online_bytes_p0"], pp["online_bytes_p1"]),
                        pr["online_seconds"] - pp["online_seconds"], pr["online_rounds"]))
    if not nm or not pub or pub.get("status") != "ok" or len(pts) < 2 or len({p[3] for p in pts}) != 1:
        return None
    and_gates = nm["estimate"]["and_gates_needed"]
    (w0, b0, s0, _), (w1, b1, s1, _) = pts[0], pts[-1]
    w = pub["weights"]
    online_bytes = max(pub["online_bytes_p0"], pub["online_bytes_p1"]) + b0 + (b1 - b0) / (w1 - w0) * (w - w0)
    online_s = pub["online_seconds"] + s0 + (s1 - s0) / (w1 - w0) * (w - w0)
    return {"name": name, "sites": pub["sites"], "and_gates": and_gates,
            "prep_gb": and_gates * pub["prep_bytes_per_party_max"] / pub["and_gates"] / 1e9,
            "prep_s": and_gates / (pub["and_gates"] / pub["prep_seconds"]),
            "online_rounds": pts[0][3], "online_kb": online_bytes / 1e3, "online_s": online_s,
            "memory_tib": and_gates * pub["peak_memory"]["working_set_bytes_per_and_gate"] / 2 ** 40
            if pub.get("peak_memory") else None}


# --------------------------------------------------------------------------- #
# Bucketing error of a session: the sum over its triple requests (paper, Section 6.1 and Appendix A)
# --------------------------------------------------------------------------- #

BUCKET_RULE = ("requests: one request of .and_gates triples if .triple_requests = 1; otherwise (chunked public-model "
               "rows) the rule of the inference driver (InferParty._generate): the session setup requests "
               ".triples_session_setup + min(budget, cap) with cap = .chunk_and, every hidden layer (.sizes[1:-1]) is "
               "generated in chunks of max(1, min(width, cap // a)) sites with a = .n_and of the site item at the row's "
               "(n, f, mode), and a chunk that finds fewer triples than it needs requests max(need - available, "
               "min(cap, remaining) - available); the reconstruction must reproduce .and_gates and .triple_requests. "
               "error = sum over the requests of leak_bound(triple_request(l, sigma)) of couplet.prep.params "
               "(Lemma A.2 evaluated exactly, with the padding and bucket size that the engine chooses for l triples)")


def request_sizes(d: "Data", r: dict):
    """Sizes of the triple requests of an end-to-end row (BUCKET_RULE), or None if they cannot be reconstructed."""
    total, setup, req = r.get("and_gates"), r.get("triples_session_setup"), r.get("triple_requests")
    if not total or setup is None or not req:
        return None
    if req == 1:
        return [total]
    cfg = r["config"]
    if cfg.get("private_model"):
        return None
    site = d.rows.get(item_name(site_item(cfg["n"], cfg["f"], cfg["mode"])))
    if not site or site.get("status") != "ok":
        return None
    per, cap, widths = site["n_and"], r.get("chunk_and") or 0, list(r["sizes"][1:-1])
    if sum(widths) != r["sites"] or setup + per * r["sites"] != total:
        return None
    budget = per * r["sites"]
    sizes = [setup + (min(budget, cap) if cap else budget)]
    avail, remaining = sizes[0] - setup, budget
    for width in widths:
        chunk = width if not cap else max(1, min(width, cap // per))
        rem = remaining
        for start in range(0, width, chunk):
            need = per * min(chunk, width - start)
            if avail < need:
                want = need - avail if not cap else max(need - avail, min(cap, rem) - avail)
                sizes.append(want)
                avail += want
            avail -= need
            rem -= need
        remaining -= per * width
    if sum(sizes) != total or len(sizes) != req:
        return None
    return sizes


# Directory of the per-configuration files (<name>.json with every run and both parties' records); main() sets it

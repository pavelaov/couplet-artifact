            L.append("\\midrule")
            L.append(f"\\multicolumn{{6}}{{@{{}}p{{\\linewidth}}@{{}}}}{{Logit weights $2^k e_j$ (private model): "
                     f"{f_int(mk['masked_logits'])} masked logits, uniformity $p={f_fix(mk['p_low_nibble'], 3)}$ and "
                     f"${f_fix(mk['p_top_nibble'], 3)}$, $|z|={f_fix(abs(mk['z_ones']), 2)}$}} \\\\")

# empties this tuple; a held row is treated exactly like an entry of not_measured, and PROVENANCE.md lists it.
PENDING_ROWS = ("infer_cnn28_16_8_round_c40000000_s40_d10ms_bw100", "infer_cnn28_16_8_exact_c40000000_s40_d10ms_bw100",
                "infer_cnn28_16_8_round_c40000000_s40_d40ms_bw100", "infer_cnn28_16_8_exact_c40000000_s40_d40ms_bw100",
                "infer_mlp784_16_8_round_private_s40", "infer_mlp784_16_8_exact_private_s40")
HELD_REASON = "measured by the separate run R-CNN / R-TILE after the campaign; held back until its integration (PENDING_ROWS)"


def hold_pending(summary: dict) -> dict:
    """A copy of the summary in which every accepted row of PENDING_ROWS counts as not measured (the file is not changed)."""
    s = copy.deepcopy(summary or {})
    nm_ids = {x["id"] for x in s.get("not_measured", [])}
    held = []
    for r in s.get("e2e", []):
        if r.get("name") in PENDING_ROWS and r.get("status") == "ok":
            held.append(r["name"])
            keep = {k: r[k] for k in ("id", "name", "groups", "view", "driver", "config") if k in r}
            r.clear()
            r.update(keep, status="pending", reason=HELD_REASON)
            if r["id"] not in nm_ids:
                s.setdefault("not_measured", []).append({"id": r["id"], "status": "pending", "reason": HELD_REASON})
    if held and s.get("checks") and s["checks"].get("accepted") is not None:
        s["checks"] = dict(s["checks"], accepted=s["checks"]["accepted"] - len(held))
    s["_held"] = held
    return s


def generate(summary: dict, attacks, ppml) -> dict:
    d = Data(hold_pending(summary), attacks, ppml)
    b = build_macros(d)
    files = {"tab-units.tex": tab_units(d), "tab-keygen.tex": tab_keygen(d), "tab-keygen-note.tex": tab_keygen_note(d),
             "tab-online.tex": tab_online(d), "tab-e2e.tex": tab_e2e(d), "tab-e2e-all.tex": tab_e2e_all(d),
             "tab-attacks.tex": tab_attacks(d), "tab-attacks-core.tex": tab_attacks_core(d)}
    files["numbers.tex"] = numbers_tex(b)
    files["PROVENANCE.md"] = provenance_md(b, d)
    return files


def check_tex(text: str) -> list:
    """Structural checks of a generated file: balanced braces, one tabular* per table, no NaN."""
    problems = []
    depth = 0
    for ch in re.sub(r"\\[{}]", "", "\n".join(l for l in text.splitlines() if not l.startswith("%"))):
        depth += ch == "{"
        depth -= ch == "}"
        if depth < 0:
            problems.append("unbalanced braces")
            break
    if depth > 0:
        problems.append("unbalanced braces")
    if re.search(r"\bnan\b|\binf\b|None", text):
        problems.append("nan, inf or None in the output")
    if "\\begin{tabular*}" in text:
        if text.count("\\begin{tabular*}") != 1 or text.count("\\end{tabular*}") != 1:
            problems.append("not exactly one tabular*")
        body = text[text.index("\\begin{tabular*}"):]
        cols = re.search(r"@\{\\extracolsep\{\\fill\}\}([a-z]+)@\{\}", body).group(1)
        for line in body.splitlines():
            if line.endswith("\\\\") and "multicolumn" not in line:
                cells = line.count("&") + 1
                if cells != len(cols):
                    problems.append(f"row with {cells} cells in a table of {len(cols)} columns: {line[:60]}")
    return problems


def selftest() -> int:
    """Generate from the campaign summary (or from a minimal synthetic one) into a scratch directory and check."""
    failures = 0
    summary = rc._read_json(DEFAULT_SUMMARY) or {"units": [], "keygen": {"rows": [], "baselines": []}, "e2e": [],
                                                  "online_layers": [], "accuracy": [], "not_measured": []}
    files = generate(summary, rc._read_json(os.path.join(RAW, "attacks.json")),
                     rc._read_json(os.path.join(RAW, "attacks_ppml.json")))
    with tempfile.TemporaryDirectory(prefix="make_tables_selftest_") as tmp:
        for name, text in files.items():
            with open(os.path.join(tmp, name), "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            if name.endswith(".tex"):
                for p in check_tex(text):
                    print(f"FAIL {name}: {p}")
                    failures += 1
    checks = [(f_int(135981) == "135{,}981", "f_int"), (f_sig(0.012345) == "0.0123", "f_sig small"),
              (f_sig(12345.6) == "12{,}300", "f_sig large"), (f_fix(3.04, 1) == "3.0", "f_fix")]
    for ok, what in checks:
        if not ok:
            print(f"FAIL formatting: {what}")
            failures += 1
    macros = re.findall(r"\\newcommand\{\\(cp[A-Za-z]+)\}", files["numbers.tex"])
    if len(macros) != len(set(macros)):
        print("FAIL duplicate macros")
        failures += 1
    print(f"make_tables selftest: {len(files)} files, {len(macros)} macros, {len(checks) + len(files)} checks, "
          f"{failures} failures")
    return 1 if failures else 0


def attack_record(name: str, summary_path: str):
    """``attacks.json`` / ``attacks_ppml.json``: next to the summary (the layout of ``results/``), else in its
    parent directory (the layout of the campaign: ``raw/campaign/summary.json``, ``raw/attacks.json``)."""
    here = os.path.dirname(os.path.abspath(summary_path))
    for d in (here, os.path.dirname(here)):
        doc = rc._read_json(os.path.join(d, name))
        if doc is not None:
            return doc
    return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="tables and number macros of the Couplet evaluation")
    ap.add_argument("--summary", default=DEFAULT_SUMMARY,
                    help="campaign summary; attacks.json and attacks_ppml.json are read from its directory or "
                         "its parent")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    global CAMPAIGN_DIR
    CAMPAIGN_DIR = os.path.dirname(os.path.abspath(args.summary))
    summary = rc._read_json(args.summary)
    if summary is None:
        raise SystemExit(f"no summary at {args.summary}: run bench/run_campaign.py first")
    files = generate(summary, attack_record("attacks.json", args.summary), attack_record("attacks_ppml.json", args.summary))
    os.makedirs(args.out, exist_ok=True)
    bad = 0
    for name, text in files.items():
        if name.endswith(".tex"):
            for p in check_tex(text):
                print(f"PROBLEM {name}: {p}")
                bad += 1
        with open(os.path.join(args.out, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    n_macros = len(re.findall(r"\\newcommand", files["numbers.tex"]))
    print(f"wrote {len(files)} files to {args.out} ({n_macros} macros)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

class Book:
    def __init__(self):
        self.macros = []          # (name, text, source)
        self.missing = []         # (name, why)

    def add(self, name: str, text, source: str) -> None:
        if not re.fullmatch(r"cp[A-Z][A-Za-z]*", name):
            raise ValueError(f"bad macro name {name}")
        if any(m[0] == name for m in self.macros):
            raise ValueError(f"duplicate macro {name}")
        self.macros.append((name, text, source))

    def need(self, name: str, row, fn, source: str) -> None:
        """Add macro `name` = fn(row) if the row exists, else record it as missing."""
        if row is None:
            self.missing.append((name, source))
            return
        try:
            self.add(name, fn(row), source)
        except (KeyError, TypeError, ZeroDivisionError, ValueError) as exc:
            self.missing.append((name, f"{source} ({exc})"))



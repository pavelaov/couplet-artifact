class Data:
    def __init__(self, summary: dict, attacks: dict, ppml: dict):
        self.s = summary or {}
        self.attacks = attacks
        self.ppml = ppml
        self.rows = {}
        for sec in ("units", "e2e"):
            for r in self.s.get(sec, []):
                self.rows[r["name"]] = r
        for r in (self.s.get("keygen") or {}).get("rows", []):
            self.rows[r["name"]] = r
        self.left_out = []                   # (where, name, status, reason)
        self.estimated = []                  # (where, configuration, cell, value, rule): red cells

    def row(self, name: str, where: str):
        r = self.rows.get(name)
        if r is None or r.get("status") != "ok":
            self.left_out.append((where, name, "absent" if r is None else r["status"],
                                  "" if r is None else r.get("reason", "")))
            return None
        return r

    def baseline(self, proto: str, n: int):
        for r in (self.s.get("keygen") or {}).get("baselines", []):
            if r["protocol"] == proto and r["n"] == n and r["transport"] == "tcp_two_processes" and r["status"] == "ok":
                return r
        self.left_out.append(("tab-keygen", f"baseline/{proto}_n{n}_tcp_two_processes", "absent", ""))
        return None

    def accuracy(self, model: str):
        for r in self.s.get("accuracy", []):
            if r["name"] == model:
                return r
        return None

    def local(self, n: int, threads: int = 1):
        for r in (self.s.get("local") or {}).get("rows", []) or []:
            if r["n"] == n and r["threads"] == threads:
                return r
        return None

    def online_layer(self, n: int, f: int, mode: str):
        for r in self.s.get("online_layers", []):
            if r["n"] == n and r["f"] == f and r["mode"] == mode and r.get("status") == "ok":
                return r
        return None



def tab_keygen(d: Data) -> str:
    L = ["\\toprule",
         "$n$ & Protocol & AND & \\multicolumn{3}{c}{KB per party} & Rounds & s \\\\",
         "\\cmidrule(lr){4-6}",
         " & & gates & Msgs & Corr. & Total & & \\\\", "\\midrule"]
    first = True
    for n in TABLE_KEYGEN_N:
        rows = []
        for proto, label in (("semihonest_ds", "Semi-honest"), ("leaky_zhang", "Leaky")):
            r = d.baseline(proto, n)
            if r:
                rows.append(f" & {label} & -- & {f_sig(r['bytes_messages_per_party_max'] / 1e3)} & "
                            f"{f_sig(r['bytes_correlations_per_party_max'] / 1e3)} & "
                            f"{f_sig(r['bytes_session_per_party_max'] / 1e3)} & {f_int(r['rounds_session'])} & "
                            f"{f_sig(r['seconds_session'])} \\\\")
        r = d.row(party_name("dpf", n), "tab-keygen")
        if r:
            ph = r["phases"]
            msgs = max(sum(ph[p][f"bytes_sent_p{b}"] for p in rc.ENGINE_PHASES) for b in (0, 1))
            corr = max(sum(ph[p][f"bytes_sent_p{b}"] for p in rc.PREP_PHASES if p != "baseot") for b in (0, 1))
            rows.append(f" & \\ours & {f_int(r['n_and'])} & {f_sig(msgs / 1e3)} & {f_sig(corr / 1e3)} & "
                        f"{f_sig(r['bytes_per_party_max'] / 1e3)} & {f_int(r['rounds'])} & {f_sig(r['seconds'])} \\\\")
        if rows:
            if not first:
                L.append("\\midrule")
            first = False
            rows[0] = f"{n}" + rows[0]
            L += rows
    L.append("\\bottomrule")
    return _tab("rlrrrrrr", L, "Float: table (one column, \\small), tab:keygen.  Leaky = the one-bit-leaky protocol of Zhang et al. (our re-implementation).  One key with 2^n points in a fresh "
                               "session (base OT included in Total, rounds and seconds); Msgs = protocol messages (here: "
                               "inputs, AND openings and output checks of the circuits); Corr. = correlations (OT "
                               "extension, authenticated bits; here also leaky ANDs, bucketing and triple checks).", sep="2.5pt")



def _tab(cols: str, lines: list, comment: str, sep: str = "") -> str:
    lines = [x for i, x in enumerate(lines)
             if not (x == "\\midrule" and i + 1 < len(lines) and lines[i + 1] in ("\\midrule", "\\bottomrule"))]
    pad = f"\\setlength{{\\tabcolsep}}{{{sep}}}%\n" if sep else ""
    return (GENERATED + f"% {comment}\n" + pad + "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}" + cols + "@{}}\n"
            + "\n".join(lines) + "\n\\end{tabular*}\n")



def f_int(v) -> str:
    return f"{int(round(v)):,}".replace(",", "{,}")


def f_fix(v, d: int) -> str:
    return f"{v:,.{d}f}".replace(",", "{,}")


def f_sig(v, sig: int = 3) -> str:
    """``sig`` significant digits, no exponent, thousands separated."""
    if v == 0:
        return "0"
    d = sig - 1 - int(math.floor(math.log10(abs(v))))
    return f_fix(round(v, d), d) if d >= 0 else f_int(round(v, d))


def f_pct(v, d: int = 1) -> str:
    return f_fix(100.0 * v, d)



def _e2e_cells(r: dict, acc: dict | None) -> list:
    agree = "--"
    if acc:
        agree = f_pct(acc["prediction_agreement"] if r["config"]["mode"] == "exact" else acc["prediction_agreement_round"])
    return [f_sig(r["prep_bytes_per_party_max"] / 1e9), f_sig(r["prep_seconds"]), f_int(r["online_rounds"]),
            f_sig(max(r["online_bytes_p0"], r["online_bytes_p1"]) / 1e3), f_sig(r["online_seconds"]), f_sig(r["seconds"]),
            f"{r['bit_exact_runs']}/{r['runs_checked']}", agree]



CAMPAIGN_DIR = os.path.dirname(DEFAULT_SUMMARY)
PLANE_RULE = ("per timed run (run_campaign.timed_runs of <name>.json): the slower party by totals.infer_s, its "
              "online.plane_eval_s (plane expansion) and totals.infer_s - online.plane_eval_s (the online phase without "
              "the plane expansion); median over the timed runs")


def plane_split(r: dict):
    """(plane seconds, online seconds without the plane expansion, rule) of an end-to-end row (PLANE_RULE)."""
    doc = rc._read_json(os.path.join(CAMPAIGN_DIR, r["name"] + ".json"))
    if doc and doc.get("runs"):
        plane, rest = [], []
        for run in rc.timed_runs(doc):
            slow = max(run["records"], key=lambda x: x["totals"]["infer_s"])
            plane.append(slow["online"]["plane_eval_s"])
            rest.append(slow["totals"]["infer_s"] - slow["online"]["plane_eval_s"])
        if plane:
            return statistics.median(plane), statistics.median(rest), PLANE_RULE
    return (r["plane_eval_seconds"], r["online_seconds"] - r["plane_eval_seconds"],
            "fallback without the per-configuration file: .plane_eval_seconds and .online_seconds - .plane_eval_seconds")


def bucketing_error_log2(sizes: list, sigma: int) -> float:
    """log2 of the sum of the exact bucketing bounds of the requests (Lemma A.2 with the engine's parameters)."""
    err = sum(prep_params.leak_bound(*prep_params.triple_request(l, sigma)) for l in sizes)
    return math.log2(err.numerator) - math.log2(err.denominator)



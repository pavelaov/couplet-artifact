def masked_inputs(m0, m1, x: int, delta: int) -> list:
    """The public x_hat formed in the two ways of section 5.3 (dealer-style shares of x).

    Shared-input mode: additive shares of x and of r modulo 2^n.  Wire mode
    (material with an authenticated offset): [[x]] over Z_{2^w} reduced to
    Z_{2^(n+s)} plus [[r']]; the opened value must satisfy the MAC relation.
    Returns [(mode, x_hat), ...]; both modes must give x + r mod 2^n.
    """
    n, k, s = m0.n, m0.k, m0.s
    size = 1 << n
    rp, r = offset(m0, m1)
    x0 = RNG.randrange(size)
    x1 = (x - x0) % size
    out = [("shared", ((x0 + m0.rp_share) % size + (x1 + m1.rp_share) % size) % size)]
    if m0.auth_input:
        w = k + s
        # a wire may carry any representative of x modulo 2^n (it need not be exact)
        rep = x + (RNG.getrandbits(w - n) << n)
        xs = deal(rep, delta, w, rng=RNG)
        masked = [xs[b].reduce(n, s) + AShare(m.rp_share, m.rp_tag_share, n + s)
                  for b, m in enumerate((m0, m1))]
        opened, mac = reconstruct(*masked)
        check_eq(mac, delta * opened % (1 << (n + s)), "wire mode: MAC relation of the masked opening")
        check_eq(opened, (rep + rp) % (1 << (n + s)), "wire mode: the opening is x + r' in Z_(2^(n+s))")
        out.append(("wire", opened % size))
    for mode, x_hat in out:
        check_eq(x_hat, (x + r) % size, f"{mode} mode: x_hat = x + r mod 2^n")
    return out


def random_spline(n: int, k: int) -> tuple:
    size = 1 << n
    inner = sorted(RNG.sample(range(1, size), RNG.randrange(1, min(5, size - 1) + 1)))
    pts = [0] + inner + [size] if RNG.random() < 0.7 else inner + [size] if len(inner) > 1 else [0] + inner
    pieces = [(RNG.randrange(-(1 << k), 1 << k), RNG.randrange(-(1 << k), 1 << k)) for _ in pts[1:]]
    return pts, pieces


def test_formula_relu_large_and_spline_with_dealer():
    """FORMULA TEST (trusted dealer, no protocol): relu_large and linear_spline for n = k."""
    stats = {}
    for n in (4, 6, 8):
        k = n
        w = k + S
        size = 1 << n
        half = size // 2
        nonexact = total = 0
        for rep_no in range(4):
            d0, d1 = RNG.getrandbits(S), RNG.getrandbits(S)
            if rep_no == 0:
                d0 = d1 = (1 << S) - 1                           # Delta >= 2^s
            delta = d0 + d1
            for auth in (False, True):
                rp = None
                if rep_no == 1:                                  # an offset above N/2: wrap-arounds occur
                    rp = RNG.randrange(half + 1, size) + ((RNG.getrandbits(S) << n) if auth else 0)
                spec = GateSpec.relu_large(k, S, auth_input=auth)
                m0, m1 = gates.deal_gate(spec.descriptor(), delta, RNG, rp=rp)
                r = check_material(m0, m1, delta, f"dealer relu n=k={n}")
                e0, e1 = GateEval(m0, d0, full_domain=True), GateEval(m1, d1, full_domain=True)
                for x in range(size):
                    for mode, x_hat in masked_inputs(m0, m1, x, delta):
                        tag = f"FORMULA relu_large n=k={n} x={x} r={r} ({mode})"
                        a0, a1 = gates.relu_large(e0, x_hat), gates.relu_large(e1, x_hat)
                        want = x if x < half else 0
                        value = check_share(a0, a1, delta, want, k, False, tag)
                        check_eq(spec.plain(x), want, "plain ReLU")
                        # the representative is x - N (mod 2^w) exactly when x >= 0 and x + r wraps
                        wraps = x < half and x + r >= size
                        check_eq(value, (want - size) % (1 << w) if wraps else want,
                                 f"{tag}: representative in Z_(2^w)")
                        nonexact += value >= (1 << k)
                        total += 1
                        # the same function as the one-piece spline x on [0, N/2) on the same material
                        b0 = gates.linear_spline(e0, x_hat, [0, half], [(1, 0)])
                        b1 = gates.linear_spline(e1, x_hat, [0, half], [(1, 0)])
                        check_share(b0, b1, delta, want, k, False, tag + " as spline")
                # splines with their own endpoints
                for _ in range(3):
                    pts, pieces = random_spline(n, k)
                    sp = GateSpec.linear_spline(k, S, pts, pieces, auth_input=auth)
                    s0, s1 = gates.deal_gate(sp.descriptor(), delta, RNG)
                    rs = check_material(s0, s1, delta, f"dealer spline n=k={n}")
                    f0, f1 = GateEval(s0, d0, full_domain=True), GateEval(s1, d1, full_domain=True)
                    table = gates.spline_table(n, k, pts, pieces)
                    for x in range(size):
                        for mode, x_hat in masked_inputs(s0, s1, x, delta):
                            tag = f"FORMULA linear_spline n=k={n} x={x} r={rs} ({mode})"
                            want = gates.plain_linear_spline(x, k, pts, pieces)
                            check_eq(table[x], want, "spline table helper")
                            value = check_share(sp.evaluate(f0, x_hat), sp.evaluate(f1, x_hat), delta,
                                                want, k, False, tag)
                            nonexact += value >= (1 << k)
                            total += 1
        check(nonexact > 0, f"n = k = {n}: some representatives exceed 2^k, so the gate is rightly not exact")
        stats[n] = (nonexact, total)
    NOTES.append("FORMULA tests (trusted dealer, not a protocol run), relu_large / linear_spline, "
                 "s = 64: " + "; ".join(f"n = k = {n}: {t} evaluations, {ne} with a representative "
                                        f">= 2^k" for n, (ne, t) in stats.items()))


def test_dealer_matches_catalogue_formulas():
    """FORMULA TEST (trusted dealer): the dealer reproduces every exact gate as well (cross-check
    of ``deal_gate`` against the gates that PART 1 verifies on protocol material)."""
    for n, k in ((3, 32), (5, 64), (4, 4)):
        size = 1 << n
        d0, d1 = (1 << S) - 1, RNG.getrandbits(S)

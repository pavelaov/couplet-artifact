def test_registry_state_machine():
    reg = Registry(b"sid")
    check_eq(reg.state, ACTIVE, "a new session is ACTIVE")
    # keys: GENERATING -> CERTIFIED
    kid = reg.begin_key()
    check_eq(kid, 0, "first key identifier")
    check_raises(StateError, lambda: reg.key(kid), "a key that is being generated cannot be used")
    check_raises(StateError, lambda: reg.key(7), "unknown key")
    rec = reg.certify_key(kid, "KEY", family="dpf", n=4)
    check_eq((rec.state, reg.key(kid).key, reg.key(kid).info["n"]), (CERTIFIED, "KEY", 4), "certified key")
    check_raises(StateError, lambda: reg.certify_key(kid, "KEY2"), "a key is certified once")
    check_raises(StateError, lambda: reg.certify_key(99, "KEY"), "certifying an unknown key")
    # monotone identifiers
    check_eq(reg.begin_key(5), 5, "an explicit larger identifier is accepted")
    check_raises(StateError, lambda: reg.begin_key(5), "an identifier is never issued twice")
    check_raises(StateError, lambda: reg.begin_key(3), "identifiers are monotone")
    check_eq(reg.begin_key(), 6, "automatic identifiers continue after the largest one")
    check_eq(reg.begin_key(None, 3), 7, "a block of identifiers")
    check_eq(reg.counters()["next"]["kid"], 10, "next key identifier")
    check_raises(ValueError, lambda: reg.begin_key(-1), "negative identifier")
    check_raises(ValueError, lambda: reg.begin_key(True), "bool identifier")
    check_eq([reg.next_qid() for _ in range(3)], [0, 1, 2], "query identifiers")
    # gates: GENERATING -> CERTIFIED -> USED
    gid = reg.begin_gate()
    check_raises(StateError, lambda: reg.use_gate(gid), "a gate that is being generated cannot be masked")
    check_raises(StateError, lambda: reg.use_gate(42), "unknown gate")
    reg.certify_gate(gid, "MAT", "SPEC", "EVAL")
    check_eq(reg.gate(gid).state, CERTIFIED, "certified gate")
    check_raises(StateError, lambda: reg.masked_gate(gid), "Apply before Mask")
    check_raises(StateError, lambda: reg.set_masked(gid, 3, "shared"), "no Mask in progress")
    rec = reg.use_gate(gid)
    check_eq(rec.state, USED, "Mask marks the gate USED")
    check_raises(GateUsedError, lambda: reg.use_gate(gid), "one Mask per gate")
    check_raises(StateError, lambda: reg.masked_gate(gid), "a gate whose Mask did not complete cannot be applied")
    reg.set_masked(gid, 3, "shared")
    check_eq((reg.masked_gate(gid).x_hat, reg.masked_gate(gid).mode), (3, "shared"), "masked input recorded")
    check_raises(StateError, lambda: reg.set_masked(gid, 4, "shared"), "x_hat is recorded once")
    check_raises(GateUsedError, lambda: reg.use_gate(gid), "still one Mask per gate")
    # a Mask that fails after use_gate leaves the gate USED and unusable (caught exception, retry)
    g2 = reg.begin_gate()
    reg.certify_gate(g2, "MAT2")
    try:
        reg.use_gate(g2)
        raise RuntimeError("the opening failed")              # simulated failure of the caller
    except RuntimeError:
        pass
    check_raises(GateUsedError, lambda: reg.use_gate(g2), "a failed Mask is not retried")
    check_raises(StateError, lambda: reg.masked_gate(g2), "a failed Mask yields no input")
    check_eq(reg.summary(), {"state": ACTIVE, "keys": {GENERATING: 5, CERTIFIED: 1},
                             "gates": {GENERATING: 0, CERTIFIED: 0, USED: 2}}, "summary")
    # ABORTED is absorbing; material is dropped
    g3 = reg.begin_gate()
    reg.certify_gate(g3, "MAT3")
    reg.abort()
    check_eq(reg.state, ABORTED, "abort")
    for fn, msg in ((lambda: reg.begin_key(), "begin_key"), (lambda: reg.key(kid), "key"),
                    (lambda: reg.begin_gate(), "begin_gate"), (lambda: reg.use_gate(g3), "use_gate"),
                    (lambda: reg.gate(g3), "gate"), (lambda: reg.masked_gate(gid), "masked_gate"),
                    (lambda: reg.next_qid(), "next_qid"), (lambda: reg.certify_key(5, "K"), "certify_key"),
                    (lambda: reg.require_active(), "require_active")):
        check_raises(ProtocolAbort, fn, f"after abort: {msg}")
    check(all(r.key is None for r in reg._keys.values())
          and all(r.material is None and r.evaluator is None for r in reg._gates.values()),
          "abort drops key and gate material")
    reg.abort()
    check_eq(reg.state, ABORTED, "ABORTED is absorbing")
    check_raises(ValueError, lambda: Registry("not bytes"), "sid type")


def test_registry_persistence():
    tmp = tempfile.mkdtemp(prefix="couplet-test-state-")
    path = os.path.join(tmp, "state.json")
    try:
        reg = Registry(b"sid-A", path)
        check(os.path.exists(path), "the state file is created at once")
        gids = [reg.begin_gate() for _ in range(3)]
        for g in gids:
            reg.certify_gate(g, f"MAT{g}")
        reg.use_gate(gids[0])
        reg.begin_key()
        for _ in range(5):
            reg.next_qid()
        stored = json.loads(read_text(path))
        check_eq(stored["sid"], b"sid-A".hex(), "the file names its session")
        check(all(stored["reserved"][kind] > reg.counters()["next"][kind] - 1 for kind in ("kid", "gid", "qid")),
              "the stored bound is above every identifier in use (write-ahead)")
        check_eq(stored["starts"], 1, "first process")
        # restart: a new process on the same file
        reg2 = Registry(b"sid-A", path)
        c2 = reg2.counters()
        check_eq(c2["starts"], 2, "second process")
        check(all(c2["floor"][kind] >= reg.counters()["next"][kind] for kind in ("kid", "gid", "qid")),
              "the restarted process starts above every identifier of the first one")
        for g in gids:                                          # used or not: no old gate can be masked
            check_raises(StateError, lambda g=g: reg2.use_gate(g), "a gate of the earlier process is gone")
            check_raises(StateError, lambda g=g: reg2.begin_gate(g), "its identifier cannot be issued again")
        new = reg2.begin_gate()
        check(new > max(gids) and new >= c2["floor"]["gid"], "a fresh gate gets a fresh identifier")
        check(reg2.next_qid() >= 5 and reg2.begin_key() >= 1, "all three counters are monotone across restarts")
        # many identifiers: the bound on disk always stays ahead
        for _ in range(300):
            g = reg2.begin_gate()
            check(json.loads(read_text(path))["reserved"]["gid"] > g, "write-ahead bound")
        # third process after the second one: again above
        reg3 = Registry(b"sid-A", path)
        check(reg3.begin_gate() > g, "third process continues above the second")
        # an aborted session stays aborted across restarts
        reg3.abort()
        reg4 = Registry(b"sid-A", path)
        check_eq(reg4.state, ABORTED, "ABORTED is persisted")
        check_raises(ProtocolAbort, lambda: reg4.begin_gate(), "no gate after a persisted abort")
        # a file of another session, or a damaged file, is refused and left untouched
        before = read_text(path)
        check_raises(ValueError, lambda: Registry(b"sid-B", path), "state file of another session")
        check_eq(read_text(path), before, "the foreign file is not overwritten")
        bad = os.path.join(tmp, "bad.json")
        for content in ("", "{", '{"format": "other"}',
                        '{"format": "couplet-state-1", "sid": "00", "state": "ACTIVE", '
                        '"reserved": {"kid": -1, "gid": 0, "qid": 0}, "starts": 1}'):
            with open(bad, "w", encoding="utf-8") as fh:
                fh.write(content)
            check_raises(ValueError, lambda: Registry(b"\x00", bad), "unreadable state file")
            check_eq(read_text(bad), content, "a damaged file is not reset")
        check(not os.path.exists(path + ".tmp"), "no temporary file is left behind")
    finally:
        for name in os.listdir(tmp):
            os.remove(os.path.join(tmp, name))
        os.rmdir(tmp)


def main() -> int:
    tests = [(name, fn) for name, fn in globals().items() if name.startswith("test_") and callable(fn)]
    if "-k" in sys.argv:
        key = sys.argv[sys.argv.index("-k") + 1]
        tests = [(name, fn) for name, fn in tests if key in name]
    failed = []
    start = time.perf_counter()
    print(f"gate evaluation and state machine tests, {len(tests)} test functions (domains up to n = {MAX_N})")
    for name, fn in tests:
        before = CHECKS
        t = time.perf_counter()
        try:
            fn()
        except Exception:  # noqa: BLE001 - report every failure and continue
            failed.append(name)
            print(f"  FAIL {name}")
            traceback.print_exc()
            continue
        print(f"  ok   {name:<48} {CHECKS - before:>8} checks {time.perf_counter() - t:7.1f} s", flush=True)
    elapsed = time.perf_counter() - start
    for note in NOTES:
        print("  note:", note)
    if failed:
        print(f"FAILED: {len(failed)} of {len(tests)} tests ({', '.join(failed)}); {CHECKS} checks run, {elapsed:.1f} s")
        return 1
    print(f"TOTAL CHECKS: {CHECKS}  ({len(tests)} tests, all passed, {elapsed:.1f} s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

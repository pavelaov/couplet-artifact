def check(cond, msg: str = "") -> None:
    global CHECKS
    CHECKS += 1
    if not cond:
        raise AssertionError(msg or "check failed")


def check_eq(got, exp, msg: str = "") -> None:
    global CHECKS
    CHECKS += 1
    if got != exp:
        raise AssertionError(f"{msg}: got {got!r}, expected {exp!r}")


def check_raises(exc, fn, msg: str = "") -> None:
    global CHECKS
    CHECKS += 1
    try:
        fn()
    except exc:
        return
    raise AssertionError(f"{msg}: did not raise {exc.__name__}")


def check_share(a0: AShare, a1: AShare, delta: int, want: int, k: int, exact: bool, tag) -> int:
    """One gate output: representative, MAC relation with the unreduced key, exactness flag.

    Returns the reconstructed representative in Z_{2^w}.
    """
    global CHECKS
    CHECKS += 1
    mod = 1 << a0.bits
    value = (a0.value + a1.value) % mod
    if a0.bits != a1.bits or a0.exact is not exact or a1.exact is not exact:
        raise AssertionError(f"{tag}: metadata (bits, exact) of the two shares")
    if (value if exact else value % (1 << k)) != want:
        raise AssertionError(f"{tag}: reconstructed {value}, expected {want}"
                             f"{'' if exact else ' mod 2^k'}")
    if (a0.mac + a1.mac) % mod != delta * value % mod:
        raise AssertionError(f"{tag}: MAC relation with Delta_0 + Delta_1")
    return value


def run_session(k: int, script, delta_shares=(None, None)):
    """Run ``script(role, session)`` at both parties on an ideal-preprocessing session."""
    dealer = IdealDealer()
    sid = b"test-gates-" + secrets.token_bytes(8)

    def party(role):
        def fn(chan):
            ses = Session(role, chan, sid, k=k, s=S, prep="ideal", dealer=dealer,
                          delta_share=delta_shares[role])
            ses.setup()
            return ses.delta_share, script(role, ses)
        return fn

    (d0, out0), (d1, out1), st0, st1 = run_two_party(party(0), party(1), timeout=3600)
    return out0, out1, d0 + d1, (d0, d1), st0


def drop_caches() -> None:
    """Release the cached circuits and plans (the large ones take gigabytes)."""
    for module, name in ((pg, "_CIRCUIT_CACHE"), (abb, "_PLAN_CACHE")):
        cache = getattr(module, name, None)
        if cache is not None:
            cache.clear()


def read_text(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def offset(m0, m1) -> tuple:
    """(r', r) reconstructed from the two parties' material (test only)."""
    rp = (m0.rp_share + m1.rp_share) % (1 << m0.rp_bits)
    return rp, rp % (1 << m0.n)


def check_material(m0, m1, delta: int, tag: str) -> int:
    """Structural invariants of one generated gate (both parties); returns r."""
    n, k, s = m0.n, m0.k, m0.s
    w = k + s
    size = 1 << n
    rp, r = offset(m0, m1)
    check_eq((m0.role, m1.role, m0.descriptor), (0, 1, m1.descriptor), f"{tag}: roles and descriptor")
    if m0.auth_input:
        check_eq(m0.rp_bits, n + s, f"{tag}: [[r']] lives in Z_(2^(n+s))")
        check_eq((m0.rp_tag_share + m1.rp_tag_share) % (1 << (n + s)), delta * rp % (1 << (n + s)),
                 f"{tag}: MAC of r' with the unreduced key")
    else:
        check(m0.rp_bits == n and m0.rp_tag_share is None, f"{tag}: unauthenticated offset mod 2^n")
    for i, (c, payload) in enumerate(m0.thresholds):
        wv = (m0.w_shares[i][0] + m1.w_shares[i][0]) % (1 << w)
        wt = (m0.w_shares[i][1] + m1.w_shares[i][1]) % (1 << w)
        check_eq((wv, wt), (int(r + c >= size), delta * int(r + c >= size) % (1 << w)),
                 f"{tag}: [[w_c]] for c = {c}")
        if payload == "r":
            rv = (m0.rw_shares[i][0] + m1.rw_shares[i][0]) % (1 << w)
            rt = (m0.rw_shares[i][1] + m1.rw_shares[i][1]) % (1 << w)
            check_eq((rv, rt), (r * int(r + c >= size), delta * r * int(r + c >= size) % (1 << w)),
                     f"{tag}: [[r w_c]] for c = {c}")
    for j, (a, b) in enumerate(zip(m0.outmask_shares, m1.outmask_shares)):
        check(all(x % (1 << k) == 0 for x in a + b), f"{tag}: output mask shares are multiples of 2^k")
        value = (a[0] + b[0]) % (1 << w)
        check_eq((a[1] + b[1]) % (1 << w), delta * value % (1 << w), f"{tag}: MAC of output mask {j}")
    check(pg.GateMaterial.from_bytes(m0.to_bytes()) == m0, f"{tag}: material encoding round trip")
    return r



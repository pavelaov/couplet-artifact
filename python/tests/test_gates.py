"""Tests for couplet.gates: local evaluation of the catalogue gates (DESIGN.md section 6,
Theorem 4) and couplet.state (section 5.4).

PART 1 - material generated by the protocol.  For n in {3, 4, 5, 6} and k in
{32, 64} (s = 64) one session with IDEAL preprocessing runs Pi_Gen
(``protocol.gen_gate``, i.e. the real generation circuits on the Boolean
engine) for

  * a table gate (one payload-1 DPF), three fresh instances, and two more with
    an authenticated input offset;
  * ONE gate that holds a payload-1 DCF for EVERY threshold c in [0, N], two
    or three fresh instances (fresh offsets r);
  * single comparison, interval and sign gates built from the descriptor
    constructors.

For every instance, every x in [N] (with x_hat = x + r mod N) the two parties'
local evaluations are reconstructed in Z_{2^w} and compared with the
plaintext function: zero test, equality for every c, tables (random, ReLU,
sign, identity, all-ones), comparison for EVERY c in [0, N], interval for ALL
p <= q, multi-interval, non-negativity and MSB.  Each check verifies the full
representative (exact gates must reconstruct to G(x) itself, below 2^k), the
MAC relation with the unreduced Delta = Delta_0 + Delta_1, and the exactness
flag.  The k = 32 sessions use Delta_0 = Delta_1 = 2^s - 1 (Delta >= 2^s).

PART 2 - FORMULA TESTS with a trusted dealer (clearly not a protocol run).
``relu_large`` and ``linear_spline`` need n = k and their generation circuits
for k = 32 are too large for a test, so their local-evaluation formulas are
checked on keys from ``fss.dcf_gen`` with payloads 1 and r (``gates.deal_gate``)
for n = k in {4, 6, 8}, s = 64, all x, several r, with the masked input formed
in both ways: from additive shares of x and r (shared-input mode) and from an
authenticated sharing [[x]] plus [[r']] over Z_{2^(n+s)} (wire mode).  One
protocol run with k = n = 4 ties the dealer to Pi_Gen: ``relu_large`` and a
spline on material from the generation circuit.

PART 3 - the state machine of ``couplet.state.Registry``: transitions,
monotone identifiers, one Mask per gate, abort, persistence across restarts.

Memory: the n = 6 gate with 65 DCFs is one circuit of about 63 million gates;
generating it needs about 14 GB.  ``--max-n 5`` (about 6 GB) or ``--max-n 4``
skip the larger domains.  Run from artifact/python:  python tests/test_gates.py
(``-k name`` selects tests).  Prints the number of checks; exits non-zero on
any failure.
"""


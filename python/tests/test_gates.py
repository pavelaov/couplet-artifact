        specs = [GateSpec.zero_test(n, k, S), GateSpec.equality(n, k, S, RNG.randrange(size)),
                 GateSpec.table(n, k, S, table, auth_input=True),
                 GateSpec.comparison(n, k, S, RNG.randrange(size + 1)),
                 GateSpec.comparison(n, k, S, 0), GateSpec.comparison(n, k, S, size),
                 GateSpec.interval(n, k, S, 1, size - 2, auth_input=True),
                 GateSpec.multi_interval(n, k, S, [0, 1, size // 2, size]),
                 GateSpec.nonneg(n, k, S), GateSpec.msb(n, k, S, auth_input=True)]
        for spec in specs:
            for _ in range(3):
                m0, m1 = gates.deal_gate(spec.descriptor(), delta, RNG)
                r = check_material(m0, m1, delta, f"dealer {spec.kind}")
                e0, e1 = GateEval(m0, d0), GateEval(m1, d1)
                for x in range(size):
                    for mode, x_hat in masked_inputs(m0, m1, x, delta):
                        out0, out1, want = spec.evaluate(e0, x_hat), spec.evaluate(e1, x_hat), spec.plain(x)
                        if spec.kind == "multi_interval":
                            check_eq(len(out0), spec.n_outputs, "multi-interval output count")
                            for a, b, v in zip(out0, out1, want):
                                check_share(a, b, delta, v, k, True, f"FORMULA {spec.kind} x={x} r={r}")
                        else:
                            check_share(out0, out1, delta, want, k, spec.exact,
                                        f"FORMULA {spec.kind} n={n} k={k} x={x} r={r} ({mode})")



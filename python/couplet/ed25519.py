"""The Edwards25519 group for the base OT (DESIGN.md 7.1).

Curve: -x^2 + y^2 = 1 + d x^2 y^2 over GF(p), p = 2^255 - 19,
d = -121665/121666.  The curve group has order 8 q with
q = 2^252 + 27742317777372353535851937790883648493 prime; the protocols use
the subgroup of order q generated by the standard base point ``B``.

Points are tuples (X, Y, Z, T) of Python ints in extended homogeneous
coordinates (x = X/Z, y = Y/Z, x y = T/Z), every coordinate reduced mod p.
The addition and doubling formulas are the complete ones of RFC 8032,
section 5.1.4, so they are valid for all inputs, including the identity and
points of small order.  Encoding is the standard 32-byte compressed form of
RFC 8032 (y little-endian, sign of x in the top bit); ``decompress`` rejects
non-canonical y, y that are not on the curve and "x = 0 with sign bit 1".

``hash_to_group`` maps (tag, msg) to a non-identity element of the order-q
subgroup by try-and-increment: SHA-256 output is decoded as a compressed
point; decoding failures are skipped; the point is multiplied by the cofactor
8; the identity is skipped.  The discrete logarithm of the result is unknown.

Scalar multiplication uses windows over Python integers and is NOT constant
time: its running time depends on the scalar.  Side channels are out of scope
for this artifact (DESIGN.md 1 and 7.1); do not reuse this code where they
matter.
"""

from __future__ import annotations

import secrets

from .hashes import sha256

P = 2**255 - 19
Q = 2**252 + 27742317777372353535851937790883648493
COFACTOR = 8
POINT_BYTES = 32

D = (-121665 * pow(121666, P - 2, P)) % P
_D2 = (2 * D) % P
_SQRT_M1 = pow(2, (P - 1) // 4, P)

Point = tuple[int, int, int, int]

IDENTITY: Point = (0, 1, 1, 0)


# --------------------------------------------------------------------------- #
# Group law
# --------------------------------------------------------------------------- #

def add(p1: Point, p2: Point) -> Point:
    """p1 + p2 (complete addition, RFC 8032 section 5.1.4)."""
    x1, y1, z1, t1 = p1
    x2, y2, z2, t2 = p2
    a = (y1 - x1) * (y2 - x2) % P
    b = (y1 + x1) * (y2 + x2) % P
    c = t1 * _D2 % P * t2 % P
    d = 2 * z1 * z2 % P
    e, f, g, h = b - a, d - c, d + c, b + a
    return (e * f % P, g * h % P, f * g % P, e * h % P)


def double(p1: Point) -> Point:
    """2 * p1 (RFC 8032 section 5.1.4)."""
    x1, y1, z1, _ = p1
    a = x1 * x1 % P
    b = y1 * y1 % P
    c = 2 * z1 * z1 % P
    h = a + b
    e = h - (x1 + y1) * (x1 + y1) % P
    g = a - b
    f = c + g
    return (e * f % P, g * h % P, f * g % P, e * h % P)


def neg(p1: Point) -> Point:
    """-p1."""
    x1, y1, z1, t1 = p1
    return ((-x1) % P, y1, z1, (-t1) % P)


def sub(p1: Point, p2: Point) -> Point:
    """p1 - p2."""
    return add(p1, neg(p2))


def equal(p1: Point, p2: Point) -> bool:
    """True iff the two representations denote the same point."""
    x1, y1, z1, _ = p1
    x2, y2, z2, _ = p2
    return (x1 * z2 - x2 * z1) % P == 0 and (y1 * z2 - y2 * z1) % P == 0


def is_identity(p1: Point) -> bool:
    """True iff p1 is the neutral element (0, 1)."""
    x1, y1, z1, _ = p1
    return x1 % P == 0 and (y1 - z1) % P == 0


def is_on_curve(p1: Point) -> bool:
    """Check the curve equation and the T coordinate of a representation."""
    x1, y1, z1, t1 = p1
    if z1 % P == 0:
        return False
    xx, yy, zz = x1 * x1 % P, y1 * y1 % P, z1 * z1 % P
    return ((yy - xx) * zz - zz * zz - D * xx % P * yy) % P == 0 and (t1 * z1 - x1 * y1) % P == 0


def scalar_mult(k: int, p1: Point) -> Point:
    """k * p1 for any integer k (4-bit fixed windows; variable time).

    The scalar is not reduced modulo q, so the function is correct for points
    outside the prime-order subgroup as well (e.g. for the test q * P = 0).
    """
    k = int(k)
    if k < 0:
        k, p1 = -k, neg(p1)
    table = [IDENTITY, p1]
    for _ in range(14):
        table.append(add(table[-1], p1))
    acc = IDENTITY
    for shift in range(((k.bit_length() + 3) // 4 - 1) * 4, -4, -4):
        acc = double(double(double(double(acc))))
        nibble = (k >> shift) & 15
        if nibble:
            acc = add(acc, table[nibble])
    return acc


def clear_cofactor(p1: Point) -> Point:
    """8 * p1: maps every curve point into the subgroup of order q."""
    return double(double(double(p1)))


def in_subgroup(p1: Point) -> bool:
    """True iff q * p1 is the identity (membership in the prime-order subgroup)."""
    return is_identity(scalar_mult(Q, p1))


# --------------------------------------------------------------------------- #
# Encoding
# --------------------------------------------------------------------------- #

def _recover_x(y: int, sign: int) -> int | None:
    """x with x^2 = (y^2 - 1) / (d y^2 + 1) and parity ``sign``; None if there is none."""
    if y >= P:
        return None
    x2 = (y * y - 1) * pow(D * y * y + 1, P - 2, P) % P
    if x2 == 0:
        return None if sign else 0
    x = pow(x2, (P + 3) // 8, P)
    if (x * x - x2) % P != 0:
        x = x * _SQRT_M1 % P
    if (x * x - x2) % P != 0:
        return None
    if (x & 1) != sign:
        x = P - x
    return x


def compress(p1: Point) -> bytes:
    """Standard 32-byte encoding: y little-endian with the parity of x in bit 255."""
    x1, y1, z1, _ = p1
    zinv = pow(z1, P - 2, P)
    x = x1 * zinv % P
    y = y1 * zinv % P
    return (y | ((x & 1) << 255)).to_bytes(POINT_BYTES, "little")


def decompress(data: bytes) -> Point:
    """Decode a 32-byte encoding; raises ``ValueError`` if it is not a curve point.

    The result is a point of the full curve group (order 8 q); use
    ``decompress_subgroup`` for data received from the other party.
    """
    if len(data) != POINT_BYTES:
        raise ValueError("a point encoding is 32 bytes")
    y = int.from_bytes(data, "little")
    sign = y >> 255
    y &= (1 << 255) - 1
    x = _recover_x(y, sign)
    if x is None:
        raise ValueError("not a valid Edwards25519 point encoding")
    return (x, y, 1, x * y % P)


def decompress_subgroup(data: bytes, allow_identity: bool = True) -> Point:
    """Decode and check membership in the order-q subgroup; ``ValueError`` otherwise."""
    p1 = decompress(data)
    if not in_subgroup(p1):
        raise ValueError("point is not in the prime-order subgroup")
    if not allow_identity and is_identity(p1):
        raise ValueError("identity point not allowed")
    return p1


# --------------------------------------------------------------------------- #
# Base point
# --------------------------------------------------------------------------- #

_BY = 4 * pow(5, P - 2, P) % P
_BX = _recover_x(_BY, 0)
B: Point = (_BX, _BY, 1, _BX * _BY % P)

_BASE_TABLE: list[list[Point]] | None = None


def _base_table() -> list[list[Point]]:
    """table[i][j] = j * 16^i * B for i < 64 and j < 16 (built on first use)."""
    global _BASE_TABLE
    if _BASE_TABLE is None:
        table = []
        cur = B
        for _ in range(64):
            row = [IDENTITY, cur]
            for _ in range(14):
                row.append(add(row[-1], cur))
            table.append(row)
            cur = add(row[15], cur)  # 16 * cur
        _BASE_TABLE = table
    return _BASE_TABLE


def base_mult(k: int) -> Point:
    """k * B with a precomputed table (k is reduced modulo q; variable time)."""
    k = int(k) % Q
    table = _base_table()
    acc = IDENTITY
    i = 0
    while k:
        nibble = k & 15
        if nibble:
            acc = add(acc, table[i][nibble])
        k >>= 4
        i += 1
    return acc


# --------------------------------------------------------------------------- #
# Scalars and hashing to the group
# --------------------------------------------------------------------------- #

def random_scalar() -> int:
    """Uniform scalar in [1, q - 1] from the OS CSPRNG."""
    return secrets.randbelow(Q - 1) + 1


def hash_to_group(tag: bytes, msg: bytes) -> Point:
    """Hash (tag, msg) to a non-identity element of the order-q subgroup.

    Try-and-increment: for ctr = 0, 1, ... the 32 bytes
    ``sha256("Couplet-h2g", tag, msg, ctr as 4 bytes little-endian)`` (framed
    as in ``couplet.hashes.sha256``) are decoded as a compressed point; on a
    decoding failure the counter is incremented.  The decoded point is
    multiplied by the cofactor 8 and returned unless it is the identity.
    About two attempts are needed on average.
    """
    ctr = 0
    while True:
        digest = sha256(b"Couplet-h2g", tag, msg, ctr.to_bytes(4, "little"))
        ctr += 1
        try:
            candidate = decompress(digest)
        except ValueError:
            continue
        point = clear_cofactor(candidate)
        if not is_identity(point):
            return point

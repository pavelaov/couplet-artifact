def _assemble_key(family: str, role: int, n: int, k: int, s: int, out: dict, prefix: str, j: int):
    """Party ``role``'s key of instance ``j`` from the opened outputs under ``prefix``."""
    width = k + s
    seed_mask, word_mask = (1 << SEED_BITS) - 1, (1 << width) - 1
    cws, cwtl, cwtr = out[prefix + "cws"][j], out[prefix + "cwtl"][j], out[prefix + "cwtr"][j]
    common = dict(
        b=role, n=n, k=k, s=s, seed=fss.seed_from_int(out[f"{prefix}root{role}"][j]),
        cw_s=tuple(fss.seed_from_int((cws >> (SEED_BITS * i)) & seed_mask) for i in range(n)),
        cw_tl=tuple((cwtl >> i) & 1 for i in range(n)),
        cw_tr=tuple((cwtr >> i) & 1 for i in range(n)),
        cw_out_v=out[prefix + "cwout_v"][j], cw_out_t=out[prefix + "cwout_t"][j])
    if family == "dpf":
        return fss.DPFKey(**common)
    vcw, tcw = out[prefix + "vcw"][j], out[prefix + "tcw"][j]
    return fss.DCFKey(cw_v=tuple((vcw >> (width * i)) & word_mask for i in range(n)),
                      cw_t=tuple((tcw >> (width * i)) & word_mask for i in range(n)), **common)


def _assemble_gate(role: int, desc: dict, own: dict, out: dict, prefix: str, j: int) -> GateMaterial:
    """Party ``role``'s gate material of instance ``j`` under the label prefix ``prefix``."""
    n, k, s = desc["n"], desc["k"], desc["s"]

    def share(q: str, tagged: bool = True):
        """This party's share of a share_out: P_0 holds its inputs sigma, P_1 the outputs."""
        if role == 0:
            return own[q + "sigma"][j], (own[q + "mu_sigma"][j] if tagged else None)
        return out[q + "share1"][j], (out[q + "mu_share1"][j] if tagged else None)

    auth = desc["auth_input"]
    rp_share, rp_tag = share(prefix + "rp.", auth)
    dpf_key = None
    if desc["dpf_one"]:
        dpf_key = _assemble_key("dpf", role, n, k, s, out, prefix + "dpf.", j)
    dcf_keys, w_shares, rw_shares = [], [], []
    for i, (_, payload) in enumerate(desc["thresholds"]):
        q = f"{prefix}th{i}."
        dcf_keys.append(_assemble_key("dcf", role, n, k, s, out, q, j))
        w_shares.append(share(q + "w."))
        rw_shares.append(share(q + "rw.") if payload == "r" else None)
    outmasks = []
    for i in range(desc["n_outmask"]):
        value, tag = share(f"{prefix}om{i}.")          # s-bit shares of the high parts
        outmasks.append((value << k, tag << k))        # SPDZ2k shares of 2^k rho over Z_{2^w}
    return GateMaterial(role, desc, n + s if auth else n, rp_share, rp_tag, dpf_key,
                        tuple(dcf_keys), tuple(w_shares), tuple(rw_shares), tuple(outmasks))



def and_count(descriptor) -> int:
    """AND gates of ONE instance of the generation circuit of ``descriptor`` (circuit stats)."""
    desc = cg.canonical_descriptor(descriptor)
    key = json.dumps(desc, sort_keys=True)
    count = _AND_COUNTS.get(key)
    if count is None:
        count = int(generation_circuit(desc).stats()["n_and"])
        _AND_COUNTS[key] = count
    return count


def outmask_descriptor(k: int, s: int) -> dict:
    """Descriptor of the on-demand output-mask circuit: one mask ``[[2^k rho]]`` per instance.

    A gate descriptor without keys and with a single output mask (it contains
    an unused 1-bit offset because every gate descriptor has one); the circuit
    that ``AuthEval.reserve_outmasks`` and ``Open`` run on as many instances as
    masks are needed.
    """
    return cg.gate_descriptor(1, k, s, False, False, [], 1)


def outmask_and_count(k: int, s: int) -> int:
    """AND triples consumed by ONE on-demand output mask."""
    return and_count(outmask_descriptor(k, s))


def _planned(call: str, descriptor, batch) -> dict:
    batch = _check_batch(batch)
    desc = cg.canonical_descriptor(descriptor)
    n_and = and_count(desc)
    return {"call": call, "descriptor": desc, "batch": batch, "n_and": n_and,
            "triples": n_and * batch}


def planned_key(family: str, n: int, k: int, s: int, index_mode: str = "xor",
                beta_mode: str = "public_one", batch: int = 1, adder: str = "ripple") -> dict:
    """Planned ``gen_dpf`` / ``gen_dcf`` call on a session with these ``k`` and ``s``."""
    if family not in ("dpf", "dcf"):
        raise ValueError("family must be 'dpf' or 'dcf'")
    make = cg.dpf_descriptor if family == "dpf" else cg.dcf_descriptor
    return _planned("gen_" + family, make(n, k, s, index_mode, beta_mode, adder), batch)


def planned_gate(descriptor, batch: int = 1) -> dict:
    """Planned ``gen_gate`` call; ``descriptor`` is a gate descriptor or an object with ``descriptor()``."""
    if not isinstance(descriptor, dict) and hasattr(descriptor, "descriptor"):
        descriptor = descriptor.descriptor()
    desc = cg.canonical_descriptor(descriptor)
    if desc["kind"] != "gate":
        raise ValueError("expected a gate descriptor")
    return _planned("gen_gate", desc, batch)


def planned_batch(k: int, s: int, items, adder: str = "ripple") -> dict:
    """Planned ``gen_batch`` call (``items`` as for ``gen_batch``) on a session with ``k`` and ``s``."""
    descs = []
    for item in list(items):
        kind = item.get("kind") if isinstance(item, dict) else None
        if kind in ("dpf", "dcf"):
            make = cg.dpf_descriptor if kind == "dpf" else cg.dcf_descriptor
            descs.append(make(item["n"], k, s, item.get("index_mode", "xor"),
                              item.get("beta_mode", "public_one"), adder))
        elif kind == "gate":
            descs.append(cg.canonical_descriptor(item["descriptor"]))
        else:
            raise ValueError("items are made with key_request() and gate_request()")
    return _planned("gen_batch", cg.batch_descriptor(descs, adder), 1)


def planned_outmasks(k: int, s: int, count: int) -> dict:
    """``count`` on-demand output masks (in however many executions they are generated)."""
    if isinstance(count, bool) or int(count) != count or int(count) < 0:
        raise ValueError("count must be a non-negative integer")
    n_and = outmask_and_count(k, s)
    return {"call": "outmasks", "descriptor": outmask_descriptor(k, s), "batch": int(count),
            "n_and": n_and, "triples": n_and * int(count)}


def and_budget(calls) -> int:
    """AND triples consumed by the planned ``calls``: the value of ``reserve_triples``.

    ``calls`` is a sequence of planned calls (``planned_key``, ``planned_gate``,
    ``planned_batch``, ``planned_outmasks``); plain pairs ``(descriptor, batch)``
    are accepted as well.  The session-setup circuit is NOT included:
    ``Session.setup`` adds its own triples to the reservation.
    """
    total = 0
    for call in calls:
        if isinstance(call, dict) and "triples" in call:
            total += int(call["triples"])
        else:
            descriptor, batch = call
            total += and_count(descriptor) * _check_batch(batch)
    return total


def session_triples(calls, s: int, setup_adder: str = "ripple") -> int:
    """Size of the ONE triple request of a session that runs ``calls``: setup circuit plus budget."""
    return int(cg.build_session_setup(s, adder=setup_adder).stats()["n_and"]) + and_budget(calls)


def _per_instance(value, batch: int, bits: int, name: str) -> list:
    """One integer per instance from an integer or a sequence of ``batch`` integers."""
    if isinstance(value, bool):
        raise ValueError(f"{name} must be an integer or a sequence of integers")
    values = [value] * batch if isinstance(value, (int, np.integer)) else list(value)
    if len(values) != batch:
        raise ValueError(f"{name}: expected {batch} values")
    out = []
    for v in values:
        if isinstance(v, bool) or int(v) != v or not 0 <= int(v) < (1 << bits):
            raise ValueError(f"{name} must lie in [0, 2^{bits})")
        out.append(int(v))
    return out


def _check_batch(batch) -> int:
    if isinstance(batch, bool) or int(batch) != batch or int(batch) < 1:
        raise ValueError("batch must be a positive integer")
    return int(batch)


def _key_descriptor(session, family: str, n: int, index_mode: str, beta_mode: str, adder: str) -> dict:
    make = cg.dpf_descriptor if family == "dpf" else cg.dcf_descriptor
    return make(n, session.k, session.s, index_mode, beta_mode, adder)


def _gate_descriptor(session, descriptor) -> dict:
    desc = cg.canonical_descriptor(descriptor)
    if desc["kind"] != "gate":
        raise ValueError("expected a gate descriptor")
    if (desc["k"], desc["s"]) != (session.k, session.s):
        raise ValueError("the gate descriptor does not use the session's k and s")
    return desc


def _key_inputs(desc: dict, prefix: str, alpha_share, beta_share, batch: int) -> dict:
    """The non-random inputs of one key circuit: label -> one integer per instance."""
    fixed = {prefix + "alpha": _per_instance(alpha_share, batch, desc["n"], "alpha_share")}
    if desc["beta_mode"] == "secret":
        if beta_share is None:
            raise ValueError("beta_mode 'secret' needs a beta_share")
        fixed[prefix + "beta"] = _per_instance(beta_share, batch, desc["k"], "beta_share")
    elif beta_share is not None:
        raise ValueError("beta_mode 'public_one' takes no beta_share")
    return fixed


def _run(session, circuit: Circuit, fixed: dict, batch: int, rng):
    """Evaluate a generation circuit; returns (own inputs, opened outputs) as integers per instance."""
    rand = as_rand(rng)
    role = session.role
    inputs, own = {}, {}
    for owner, label, wires in circuit.inputs:
        if owner != role:
            continue
        width = len(wires)
        if label in fixed:
            bits = ints_to_bits(fixed[label], width)
        else:                                   # fresh uniform coins of this party
            bits = rand.bits(width * batch).reshape(width, batch)
        inputs[label] = bits
        own[label] = bits
    result = session.evaluate(circuit, inputs, batch=batch)
    outputs = {label: bits_to_ints(bits) for label, bits in result.public.items()}
    outputs.update({label: bits_to_ints(bits) for label, bits in result.private.items()})
    session.last_gen = {
        "circuit": circuit.meta.get("name"), "digest": circuit_digest(circuit).hex(),
        "batch": batch, "stats": dict(result.stats),
    }
    return {label: bits_to_ints(bits) for label, bits in own.items()}, outputs



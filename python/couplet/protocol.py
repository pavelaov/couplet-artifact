_GATE_MAGIC = b"CPLTGAT1"
_CIRCUIT_CACHE: "OrderedDict[str, Circuit]" = OrderedDict()
_CIRCUIT_CACHE_SIZE = 8
_CIRCUIT_LOCK = threading.Lock()   # two in-process parties build a circuit only once
_AND_COUNTS: dict = {}             # canonical descriptor (JSON) -> AND gates of one instance



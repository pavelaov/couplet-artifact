def key_request(family: str, n: int, index_mode: str = "xor", beta_mode: str = "public_one",
                alpha_share: int = 0, beta_share: Optional[int] = None) -> dict:
    """Item of ``gen_batch``: one DPF (``family = "dpf"``) or DCF (``"dcf"``) key."""
    if family not in ("dpf", "dcf"):
        raise ValueError("family must be 'dpf' or 'dcf'")
    return {"kind": family, "n": int(n), "index_mode": index_mode, "beta_mode": beta_mode,
            "alpha_share": alpha_share, "beta_share": beta_share}


def gate_request(descriptor) -> dict:
    """Item of ``gen_batch``: one gate with the given ``circuits_gen.gate_descriptor``."""
    return {"kind": "gate", "descriptor": dict(descriptor)}



"""Pi_Gen: dealer-free generation of FSS keys and gate material (DESIGN.md sections 4, 5.2).

Each function runs ONE party on its ``couplet.session.Session``; the other
party calls the same function with the same public parameters and its own
shares.  The protocol is exactly "inputs via Input, evaluate C_gen, Output"
(Theorem 1): the party

  1. builds the generation circuit of ``couplet.circuits_gen`` for the public
     parameters (deterministic; the engine compares the circuit digest with
     the peer in its first exchange);
  2. supplies its inputs: its shares of ``alpha`` / ``beta`` (keys) and fresh
     uniform coins for every other input declaration it owns (root coins
     ``rho0`` / ``rho1``, the coins of ``r'``, the output-mask coins and, for
     P_0, the ``share_out`` values ``sigma`` / ``mu_sigma``).  Coins come from
     the OS CSPRNG unless a deterministic ``rng`` (object with ``randbytes``)
     is passed for tests;
  3. evaluates the circuit on the session engine, the session wires of
     ``Delta`` being bound to the circuit's BOUND input;
  4. assembles its outputs: ``couplet.fss.DPFKey`` / ``DCFKey`` objects (own
     root from the private output, public correction words) and, for gates,
     a ``GateMaterial`` with this party's SPDZ2k shares.

Functions (``batch`` = number of independent instances generated by one
circuit execution; all instances share the rounds):

    gen_dpf(session, n, index_mode, beta_mode, alpha_share, beta_share=None, batch=1)
        -> list of ``batch`` DPFKey
    gen_dcf(...)                                    -> list of ``batch`` DCFKey
    gen_gate(session, descriptor, batch=1)          -> list of ``batch`` GateMaterial
    gen_batch(session, items)                       -> one output per item
        (several different keys / gates concatenated into ONE circuit; items
        are made with ``key_request`` and ``gate_request``)

``alpha_share`` / ``beta_share`` are integers (one per instance, or a single
integer used for every instance): XOR or additive shares of the index
(``index_mode`` ``"xor"`` / ``"add"``), additive shares mod 2^k of the payload
(``beta_mode = "secret"``; ``"public_one"`` fixes the payload to 1).

Any ``ProtocolAbort`` moves the session to ``ABORTED`` and nothing is
returned.  Returned objects are plain data: they pickle, and ``to_bytes`` /
``from_bytes`` give a canonical encoding for the two-process driver.

AND budget (triple reservation).  The statistical bound 2^-sigma of the
bucketing holds per preprocessing request, so a session should draw all its
triples in ONE request, at ``Session.setup(reserve_triples=...)``.  The helpers
below compute that number from the statistics of the generation circuits,
for a PLANNED list of generation calls, before any message is sent:

    and_count(descriptor)                 AND gates of one instance of a circuit
    planned_key(family, n, k, s, ...)     one gen_dpf / gen_dcf call
    planned_gate(descriptor, batch=1)     one gen_gate call
    planned_batch(k, s, items)            one gen_batch call
    planned_outmasks(k, s, count)         ``count`` on-demand output masks
    and_budget(calls)                     the sum: triples to reserve
    session_triples(calls, s, adder)      the same plus the session-setup circuit
                                          (the size of the one request)

A planned call is a dictionary ``{"call", "descriptor", "batch", "n_and",
"triples"}``; ``triples = n_and * batch`` because every instance of the batch
dimension consumes its own triples.

``GateMaterial`` encoding (all integers little-endian, W = ceil((k+s)/8),
M = ceil(m/8) with m = n + s for an authenticated input and n otherwise):
    8B magic "CPLTGAT1" | u8 role | u32 length of the descriptor |
    descriptor (canonical JSON of ``circuits_gen.gate_descriptor``) |
    M bytes share of r' (or of r) | [M bytes tag share, auth_input only] |
    [DPF key in the ``fss`` encoding, dpf_one only] |
    per threshold: DCF key | W bytes [[w_c]] value share | W bytes tag share |
                   [W bytes [[r w_c]] value share | W bytes tag share, payload r only] |
    per output mask: W bytes value share | W bytes tag share
"""


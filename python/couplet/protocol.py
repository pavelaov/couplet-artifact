@dataclass
class GateMaterial:
    """One party's output of Gate.Gen (DESIGN.md 4.3) for one gate instance.

    ``descriptor``      canonical gate descriptor (``circuits_gen.gate_descriptor``);
    ``rp_bits``         modulus bits m of the offset sharing: n + s with an
                        authenticated input, n otherwise;
    ``rp_share``        share of r' mod 2^(n+s) (auth_input) or of r mod 2^n;
    ``rp_tag_share``    share of Delta r' mod 2^(n+s); None without auth_input;
    ``dpf_key``         DPF key at index r with payload 1, or None;
    ``dcf_keys``        one DCF key per threshold (c, payload), at index
                        (r + c) mod 2^n with payload 1 or r;
    ``w_shares``        per threshold the share (value, tag) of [[w_c]] over
                        Z_{2^w}, w_c = [r + c >= 2^n];
    ``rw_shares``       per threshold the share of [[r w_c]] (payload r) or None;
    ``outmask_shares``  per output mask the share (value, tag) of
                        [[2^k rho]] over Z_{2^w}; both are multiples of 2^k.
    All sharings are additive: the two parties' values sum to the secret
    modulo the stated power of two, tags with Delta = Delta_0 + Delta_1.
    """

    role: int
    descriptor: dict
    rp_bits: int
    rp_share: int
    rp_tag_share: Optional[int]
    dpf_key: Optional[fss.DPFKey]
    dcf_keys: tuple
    w_shares: tuple
    rw_shares: tuple
    outmask_shares: tuple

    @property
    def n(self) -> int:
        return self.descriptor["n"]

    @property
    def k(self) -> int:
        return self.descriptor["k"]

    @property
    def s(self) -> int:
        return self.descriptor["s"]

    @property
    def width(self) -> int:
        return self.descriptor["k"] + self.descriptor["s"]

    @property
    def auth_input(self) -> bool:
        return self.descriptor["auth_input"]

    @property
    def thresholds(self) -> list:
        return [(c, payload) for c, payload in self.descriptor["thresholds"]]

    def to_bytes(self) -> bytes:
        desc = json.dumps(self.descriptor, sort_keys=True, separators=(",", ":")).encode("utf-8")
        wb = (self.width + 7) // 8
        mb = (self.rp_bits + 7) // 8
        parts = [_GATE_MAGIC, bytes([self.role]), len(desc).to_bytes(4, "little"), desc,
                 self.rp_share.to_bytes(mb, "little")]
        if self.auth_input:
            parts.append(self.rp_tag_share.to_bytes(mb, "little"))
        if self.descriptor["dpf_one"]:
            parts.append(self.dpf_key.to_bytes())
        for i, (_, payload) in enumerate(self.thresholds):
            parts.append(self.dcf_keys[i].to_bytes())
            parts += [x.to_bytes(wb, "little") for x in self.w_shares[i]]
            if payload == "r":
                parts += [x.to_bytes(wb, "little") for x in self.rw_shares[i]]
        for value, tag in self.outmask_shares:
            parts += [value.to_bytes(wb, "little"), tag.to_bytes(wb, "little")]
        return b"".join(parts)

    @classmethod
    def from_bytes(cls, data: bytes) -> "GateMaterial":
        data = bytes(data)
        pos = len(_GATE_MAGIC)
        if data[:pos] != _GATE_MAGIC or len(data) < pos + 5:
            raise ValueError("not a gate material encoding")
        role = data[pos]
        if role not in (0, 1):
            raise ValueError("party index must be 0 or 1")
        dlen = int.from_bytes(data[pos + 1:pos + 5], "little")
        pos += 5
        if pos + dlen > len(data):
            raise ValueError("truncated gate material")
        desc = cg.canonical_descriptor(json.loads(data[pos:pos + dlen].decode("utf-8")))
        if desc["kind"] != "gate":
            raise ValueError("the descriptor is not a gate descriptor")
        pos += dlen
        n, k, s = desc["n"], desc["k"], desc["s"]
        width = k + s
        wb = (width + 7) // 8
        m = n + s if desc["auth_input"] else n
        mb = (m + 7) // 8

        def take_int(nbytes: int, bits: int) -> int:
            nonlocal pos
            if pos + nbytes > len(data):
                raise ValueError("truncated gate material")
            value = int.from_bytes(data[pos:pos + nbytes], "little")
            pos += nbytes
            if value >> bits:
                raise ValueError("share out of range")
            return value

        def take_key(family_cls, key_n: int):
            nonlocal pos
            if pos + 4 > len(data):
                raise ValueError("truncated gate material")
            end = pos + 4 + int.from_bytes(data[pos:pos + 4], "little")
            if end > len(data):
                raise ValueError("truncated gate material")
            key = family_cls.from_bytes(data[pos:end])
            pos = end
            if (key.b, key.n, key.k, key.s) != (role, key_n, k, s):
                raise ValueError("embedded key does not match the descriptor")
            return key

        rp_share = take_int(mb, m)
        rp_tag = take_int(mb, m) if desc["auth_input"] else None
        dpf_key = take_key(fss.DPFKey, n) if desc["dpf_one"] else None
        dcf_keys, w_shares, rw_shares = [], [], []
        for _, payload in desc["thresholds"]:
            dcf_keys.append(take_key(fss.DCFKey, n))
            w_shares.append((take_int(wb, width), take_int(wb, width)))
            rw_shares.append((take_int(wb, width), take_int(wb, width)) if payload == "r" else None)
        outmasks = []
        for _ in range(desc["n_outmask"]):
            value, tag = take_int(wb, width), take_int(wb, width)
            if value % (1 << k) or tag % (1 << k):
                raise ValueError("output mask shares must be multiples of 2^k")
            outmasks.append((value, tag))
        if pos != len(data):
            raise ValueError("trailing bytes")
        return cls(role, desc, m, rp_share, rp_tag, dpf_key, tuple(dcf_keys), tuple(w_shares),
                   tuple(rw_shares), tuple(outmasks))

    def size_bytes(self) -> int:
        return len(self.to_bytes())



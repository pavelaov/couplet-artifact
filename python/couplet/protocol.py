def _gen_key(session, family: str, n: int, index_mode: str, beta_mode: str, alpha_share,
             beta_share, batch: int, rng, adder: str) -> list:
    session.require_active()
    batch = _check_batch(batch)
    desc = _key_descriptor(session, family, n, index_mode, beta_mode, adder)
    fixed = _key_inputs(desc, "", alpha_share, beta_share, batch)
    circuit = generation_circuit(desc)
    _, out = _run(session, circuit, fixed, batch, rng)
    return [_assemble_key(family, session.role, desc["n"], desc["k"], desc["s"], out, "", j)
            for j in range(batch)]


def gen_dpf(session, n: int, index_mode: str = "xor", beta_mode: str = "public_one",
            alpha_share=0, beta_share=None, batch: int = 1, *, rng=None, adder: str = "ripple") -> list:
    """This party's DPF keys for ``batch`` independent point functions.

    Returns a list of ``batch`` ``fss.DPFKey`` (key ``j`` belongs to
    ``alpha_share[j]`` / ``beta_share[j]``).  The two parties' keys evaluate to
    additive shares of ``beta [x = alpha]`` and of ``Delta beta [x = alpha]``
    in ``Z_{2^(k+s)}`` with ``k, s`` and ``Delta`` of the session.
    """
    return _gen_key(session, "dpf", n, index_mode, beta_mode, alpha_share, beta_share, batch, rng, adder)


def gen_dcf(session, n: int, index_mode: str = "xor", beta_mode: str = "public_one",
            alpha_share=0, beta_share=None, batch: int = 1, *, rng=None, adder: str = "ripple") -> list:
    """This party's DCF keys (comparison ``beta [x < alpha]``); as ``gen_dpf``."""
    return _gen_key(session, "dcf", n, index_mode, beta_mode, alpha_share, beta_share, batch, rng, adder)


def gen_gate(session, descriptor, batch: int = 1, *, rng=None) -> list:
    """This party's material for ``batch`` independent gates of one descriptor.

    ``descriptor`` is a ``circuits_gen.gate_descriptor`` (or ``gate_preset``)
    with the session's ``k`` and ``s``.  Returns a list of ``batch``
    ``GateMaterial``.  The gate takes no party input; a corrupted P_0 chooses
    its own ``share_out`` values, as in F_Gen.
    """
    session.require_active()
    batch = _check_batch(batch)
    desc = _gate_descriptor(session, descriptor)
    circuit = generation_circuit(desc)
    own, out = _run(session, circuit, {}, batch, rng)
    return [_assemble_gate(session.role, desc, own, out, "", j) for j in range(batch)]


def gen_batch(session, items, *, rng=None, adder: str = "ripple") -> list:
    """Several different keys and gates from ONE circuit execution (gate lists concatenated).

    ``items`` is a sequence of ``key_request(...)`` / ``gate_request(...)``
    dictionaries (one instance each).  Returns one object per item, in order:
    an ``fss.DPFKey``, an ``fss.DCFKey`` or a ``GateMaterial``.
    """
    session.require_active()
    items = list(items)
    if not items:
        raise ValueError("empty batch")
    descs, fixed = [], {}
    for j, item in enumerate(items):
        kind = item.get("kind") if isinstance(item, dict) else None
        prefix = f"i{j}."
        if kind in ("dpf", "dcf"):
            desc = _key_descriptor(session, kind, item["n"], item.get("index_mode", "xor"),
                                   item.get("beta_mode", "public_one"), adder)
            fixed.update(_key_inputs(desc, prefix, item.get("alpha_share", 0),
                                     item.get("beta_share"), 1))
        elif kind == "gate":
            desc = _gate_descriptor(session, item["descriptor"])
        else:
            raise ValueError("items are made with key_request() and gate_request()")
        descs.append(desc)
    circuit = generation_circuit(cg.batch_descriptor(descs, adder))
    own, out = _run(session, circuit, fixed, 1, rng)
    results = []
    for j, desc in enumerate(descs):
        prefix = f"i{j}."
        if desc["kind"] == "gate":
            results.append(_assemble_gate(session.role, desc, own, out, prefix, 0))
        else:
            results.append(_assemble_key(desc["kind"], session.role, desc["n"], desc["k"],
                                         desc["s"], out, prefix, 0))
    return results

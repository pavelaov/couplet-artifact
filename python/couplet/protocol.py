def generation_circuit(descriptor) -> Circuit:
    """The generation circuit of a descriptor (built once per process and cached)."""
    desc = cg.canonical_descriptor(descriptor)
    key = json.dumps(desc, sort_keys=True)
    with _CIRCUIT_LOCK:
        circuit = _CIRCUIT_CACHE.get(key)
        if circuit is None:
            circuit = cg.build(desc)
            circuit_digest(circuit)             # memoise the digest on the shared object
            _CIRCUIT_CACHE[key] = circuit
            while len(_CIRCUIT_CACHE) > _CIRCUIT_CACHE_SIZE:
                _CIRCUIT_CACHE.popitem(last=False)
        else:
            _CIRCUIT_CACHE.move_to_end(key)
    return circuit



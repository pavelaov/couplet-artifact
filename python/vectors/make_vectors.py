"""Generate the golden vectors in this directory (python vectors/make_vectors.py).

ascon_vectors.json
    Round constants, rotations, a few permutation input/output states, the
    two hash vectors used to validate the permutation, the IV words of the
    four PRG labels, and for 20 seeds the outputs of the PRG maps
    F_IV(s) = p(s || IV) XOR (s || IV) (DESIGN.md 2.1): for every label the
    raw permutation output ``perm_state`` and the feed-forward output
    ``state`` (= Y), plus the parsed outputs of G, Conv, ConvV_L, ConvV_R
    for (k, s) in {(32,64), (64,64)}.  Seeds come from
    Sha256CounterRng(ASCON_SEED).

fss_vectors.json
    12 deterministic DPF/DCF vectors: family in {DPF, DCF} x n in {4, 8, 12}
    x k in {32, 64}, s = 64.  For vector (family, n, k) the byte source is
    Sha256CounterRng(seed) with seed = SHA-256("Couplet-fss-vector/<family>/<n>/<k>");
    draws, in order: alpha = randbelow(2^n), beta = randbelow(2^k),
    delta0 = randbelow(2^s), delta1 = randbelow(2^s), then the root seeds
    s0 = randbytes(16), s1 = randbytes(16).  The MAC key is the integer
    delta = delta0 + delta1 in [0, 2^(s+1)), never reduced (it needs s+1 = 65
    bits; several vectors have delta >= 2^s).  Each entry lists the inputs,
    both keys (hex of to_bytes), a few sample Eval outputs, and SHA-256
    digests of the EvalAll vectors y_b, tau_b encoded as 2^n consecutive
    W-byte little-endian integers, W = ceil((k+s)/8).

Integers wider than 32 bits are written as "0x..." strings; byte strings as
plain hex in memory order (little-endian words).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402

from couplet import ascon, fss  # noqa: E402
from couplet.rng import Sha256CounterRng  # noqa: E402

HERE = Path(__file__).resolve().parent
DESIGN_VERSION = "3.1"
ASCON_SEED = bytes(range(32))
KS_LIST = ((32, 64), (64, 64))
FSS_CASES = [(fam, n, k) for fam in ("DPF", "DCF") for n in (4, 8, 12) for k in (32, 64)]


def hx(v: int) -> str:
    return f"0x{v:x}"


def words_hex(words) -> list[str]:
    return [f"0x{int(w):016x}" for w in words]


def conv_entry(seed: bytes, label: bytes) -> dict:
    state = ascon.prg_state(seed, label)
    entry = {"perm_state": words_hex(ascon.prg_perm_state(seed, label)), "state": words_hex(state)}
    for k, s in KS_LIST:
        v, t = ascon.conv_from_state(state, k + s)
        entry[f"k{k}_s{s}"] = {"value": hx(v), "tag": hx(t)}
    return entry


def make_ascon_vectors() -> dict:
    ascon.selftest()
    rng = Sha256CounterRng(ASCON_SEED)
    perm_inputs = [
        [0, 0, 0, 0, 0],
        [ascon.ASCON_HASH_V12_IV, 0, 0, 0, 0],
        [ascon.MASK64] * 5,
        ascon.words_from_bytes(rng.randbytes(40)),
        ascon.words_from_bytes(rng.randbytes(40)),
    ]
    perm_vectors = []
    for st in perm_inputs:
        out = ascon.permute(st)
        np_out = ascon.permute_np(*[np.array([w], dtype=np.uint64) for w in st])
        assert [int(w[0]) for w in np_out] == out
        perm_vectors.append({"input": words_hex(st), "output": words_hex(out)})
    labels = {"G": ascon.LABEL_G, "C": ascon.LABEL_C, "VL": ascon.LABEL_VL, "VR": ascon.LABEL_VR}
    prg_vectors = []
    for _ in range(20):
        seed = rng.randbytes(16)
        g_perm = ascon.prg_perm_state(seed, ascon.LABEL_G)
        g_state = ascon.prg_state(seed, ascon.LABEL_G)
        g_in = [*ascon.words_from_bytes(seed), *ascon.label_words(ascon.LABEL_G)]
        assert g_state == [a ^ b for a, b in zip(g_perm, g_in)]
        s_l, t_l, s_r, t_r = ascon.G(seed)
        lo, hi = (np.array([w], dtype=np.uint64) for w in ascon.words_from_bytes(seed))
        g_np = ascon.G_np(lo, hi)
        assert ascon.bytes_from_words((int(g_np[0][0]), int(g_np[1][0]))) == s_l and int(g_np[2][0]) == t_l
        assert ascon.bytes_from_words((int(g_np[3][0]), int(g_np[4][0]))) == s_r and int(g_np[5][0]) == t_r
        prg_vectors.append({
            "seed": seed.hex(),
            "G": {"perm_state": words_hex(g_perm), "state": words_hex(g_state),
                  "sL": s_l.hex(), "tL": t_l, "sR": s_r.hex(), "tR": t_r},
            "Conv": conv_entry(seed, ascon.LABEL_C),
            "ConvV_L": conv_entry(seed, ascon.LABEL_VL),
            "ConvV_R": conv_entry(seed, ascon.LABEL_VR),
        })
    return {
        "description": "Golden vectors for the Ascon-p12 permutation and the Couplet PRG maps "
                       "F_IV(s) = p(s||IV) XOR (s||IV) (DESIGN.md 2.1, v3.1). "
                       "Generated by python/vectors/make_vectors.py.",
        "design_version": DESIGN_VERSION,
        "format": {
            "words": "64-bit words as 0x-prefixed hex; a state is [x0, x1, x2, x3, x4]",
            "byte_strings": "hex in memory order; words are formed from 8-byte chunks little-endian",
            "seed_placement": "seed (16 bytes) -> x0, x1; label zero-padded to 24 bytes -> x2, x3, x4",
            "perm_state": "p(seed || IV): the permutation output before the feed-forward",
            "state": "Y = F_IV(seed) = perm_state XOR (seed || IV): the PRG output all maps read from",
            "G": "sL = x0||x1, sR = x2||x3 of Y (16 bytes each), tL = bit 0 of x4, tR = bit 1 of x4",
            "Conv": "Y = x0||x1||x2||x3||x4 (40 bytes) read as a little-endian integer; "
                    "value = low (k+s) bits, tag = next (k+s) bits",
            "seed_source": f"Sha256CounterRng(seed={ASCON_SEED.hex()}): two 40-byte draws for the random "
                           "permutation states, then twenty 16-byte draws for the PRG seeds",
        },
        "permutation": {
            "rounds": ascon.ROUNDS,
            "round_constants": [hx(c) for c in ascon.ROUND_CONSTANTS],
            "rotations": [list(r) for r in ascon.ROTATIONS],
            "vectors": perm_vectors,
        },
        "hash_vectors": {
            "ascon_hash_v12": {"iv": hx(ascon.ASCON_HASH_V12_IV), "byteorder": "big", "pad": "0x80",
                               "empty_message": ascon.ascon_hash_v12(b"").hex()},
            "ascon_hash256_sp800_232": {"iv": hx(ascon.ASCON_HASH256_IV), "byteorder": "little",
                                        "pad": "0x01", "empty_message": ascon.ascon_hash256(b"").hex()},
        },
        "labels": {name: {"ascii": lab.decode(), "iv_words": words_hex(ascon.label_words(lab))}
                   for name, lab in labels.items()},
        "prg_vectors": prg_vectors,
    }


def encode_vector(values, width: int) -> bytes:
    w = (width + 7) // 8
    return b"".join(int(v).to_bytes(w, "little") for v in values)


def make_fss_vectors() -> dict:
    entries = []
    for idx, (family, n, k) in enumerate(FSS_CASES):
        s = 64
        width = k + s
        mod = 1 << width
        seed = hashlib.sha256(f"Couplet-fss-vector/{family}/{n}/{k}".encode()).digest()
        rng = Sha256CounterRng(seed)
        alpha = rng.randbelow(1 << n)
        beta = rng.randbelow(1 << k)
        delta0 = rng.randbelow(1 << s)
        delta1 = rng.randbelow(1 << s)
        delta = delta0 + delta1                       # (s+1)-bit integer, never reduced
        root0 = rng.randbytes(16)
        root1 = rng.randbytes(16)
        if family == "DPF":
            gen, ev, evall = fss.dpf_gen, fss.dpf_eval, fss.dpf_eval_all
        else:
            gen, ev, evall = fss.dcf_gen, fss.dcf_eval, fss.dcf_eval_all
        k0, k1 = gen(alpha, beta, delta, n, k, s, roots=(root0, root1))
        assert (k0.seed, k1.seed) == (root0, root1)
        y0, t0 = evall(0, k0)
        y1, t1 = evall(1, k1)
        xs = np.arange(1 << n)
        ind = ((xs == alpha) if family == "DPF" else (xs < alpha)).astype(object)
        beta_t = delta * beta % mod
        assert bool(np.all((y0 + y1) % mod == (ind * beta) % mod))
        assert bool(np.all((t0 + t1) % mod == (ind * beta_t) % mod))
        samples = []
        size = 1 << n
        for x in sorted({0, size - 1, alpha, (alpha - 1) % size, (alpha + 1) % size}):
            a0, a1 = ev(0, k0, x), ev(1, k1, x)
            assert a0 == (y0[x], t0[x]) and a1 == (y1[x], t1[x])
            samples.append({"x": x, "y0": hx(a0[0]), "tau0": hx(a0[1]), "y1": hx(a1[0]), "tau1": hx(a1[1])})
        blob0, blob1 = k0.to_bytes(), k1.to_bytes()
        assert fss.key_from_bytes(blob0) == k0 and fss.key_from_bytes(blob1) == k1
        entries.append({
            "id": idx, "family": family, "n": n, "k": k, "s": s,
            "rng_seed": seed.hex(),
            "alpha": alpha, "beta": hx(beta),
            "delta0": hx(delta0), "delta1": hx(delta1), "delta": hx(delta),
            "delta_ge_2s": bool(delta >> s), "beta_t": hx(beta_t),
            "root_seed0": k0.seed.hex(), "root_seed1": k1.seed.hex(),
            "key0": blob0.hex(), "key1": blob1.hex(), "key_size_bytes": len(blob0),
            "evalall_sha256": {
                "y0": hashlib.sha256(encode_vector(y0, width)).hexdigest(),
                "tau0": hashlib.sha256(encode_vector(t0, width)).hexdigest(),
                "y1": hashlib.sha256(encode_vector(y1, width)).hexdigest(),
                "tau1": hashlib.sha256(encode_vector(t1, width)).hexdigest(),
            },
            "samples": samples,
        })
    n_big = sum(e["delta_ge_2s"] for e in entries)
    if not 0 < n_big < len(entries):
        raise AssertionError("the vector set must contain MAC keys on both sides of 2^s")
    return {
        "description": "Deterministic two-plane DPF/DCF vectors (DESIGN.md section 3, v3.1): "
                       "feed-forward PRG, final sign neg_if(t1, .), unreduced (s+1)-bit MAC key. "
                       "Generated by python/vectors/make_vectors.py.",
        "design_version": DESIGN_VERSION,
        "n_vectors_with_delta_ge_2s": n_big,
        "format": {
            "rng": "Sha256CounterRng: stream block i = SHA-256(seed || u64le(i)), i = 0,1,...; "
                   "randbytes(n) takes the next n stream bytes; randbelow(m) = u64le(randbytes(8)) mod m",
            "rng_seed": "SHA-256 of the ASCII string 'Couplet-fss-vector/<family>/<n>/<k>'",
            "draw_order": "alpha = randbelow(2^n); beta = randbelow(2^k); delta0 = randbelow(2^s); "
                          "delta1 = randbelow(2^s); s0 = randbytes(16); s1 = randbytes(16)",
            "delta": "delta = delta0 + delta1 as an integer in [0, 2^(s+1)) (65 bits for s = 64), "
                     "never reduced mod 2^s; beta_t = delta * beta mod 2^(k+s) is the tag payload",
            "key_encoding": "see couplet/fss.py module docstring (u32 length prefix, little-endian)",
            "evalall_encoding": "2^n integers in index order, each W = ceil((k+s)/8) bytes little-endian, "
                                "concatenated; digest = SHA-256 of that byte string",
            "integers": "values wider than 32 bits are 0x-prefixed hex strings",
        },
        "vectors": entries,
    }


def main() -> None:
    for name, doc in (("ascon_vectors.json", make_ascon_vectors()), ("fss_vectors.json", make_fss_vectors())):
        (HERE / name).write_text(json.dumps(doc, indent=1) + "\n", encoding="ascii", newline="\n")
    print("wrote", HERE / "ascon_vectors.json")
    print("wrote", HERE / "fss_vectors.json")


if __name__ == "__main__":
    main()
